ALTER TABLE tp_question_bank_versions ADD COLUMN IF NOT EXISTS published_by bigint;

CREATE TABLE IF NOT EXISTS tp_question_bank_drafts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  singleton boolean NOT NULL DEFAULT true CHECK (singleton),
  base_version_id bigint NOT NULL REFERENCES tp_question_bank_versions(id),
  content jsonb NOT NULL CHECK (jsonb_typeof(content) = 'object' AND jsonb_typeof(content->'questions') = 'array'),
  created_by bigint,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_question_bank_drafts_one UNIQUE (singleton)
);
