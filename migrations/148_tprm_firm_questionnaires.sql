CREATE TABLE IF NOT EXISTS tp_q_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  description text CHECK (description IS NULL OR length(description) <= 200),
  prefix text NOT NULL CHECK (prefix ~ '^[A-Z]{2,5}$'),
  draft jsonb NOT NULL DEFAULT '{"sections": [], "questions": []}'::jsonb CHECK (jsonb_typeof(draft->'sections') = 'array' AND jsonb_typeof(draft->'questions') = 'array'),
  draft_changed boolean NOT NULL DEFAULT true,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_q_templates_prefix_per_firm UNIQUE (firm_id, prefix)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tp_q_templates_name ON tp_q_templates (firm_id, lower(btrim(name)));

CREATE TABLE IF NOT EXISTS tp_q_template_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id bigint NOT NULL REFERENCES tp_q_templates(id) ON DELETE CASCADE,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  version integer NOT NULL CHECK (version >= 1),
  content jsonb NOT NULL CHECK (jsonb_typeof(content->'sections') = 'array' AND jsonb_typeof(content->'questions') = 'array'),
  question_count integer NOT NULL CHECK (question_count >= 1),
  published_by bigint,
  published_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_q_template_versions_one UNIQUE (template_id, version)
);

CREATE OR REPLACE FUNCTION tp_q_template_versions_immutable_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_q_template_versions: a published version of a firm questionnaire never changes';
  END IF;
  IF TG_OP = 'DELETE' AND EXISTS (SELECT 1 FROM tp_q_templates t WHERE t.id = OLD.template_id) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_q_template_versions: a published version of a firm questionnaire is never deleted';
  END IF;
  RETURN OLD;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_q_template_versions_immutable ON tp_q_template_versions;
CREATE TRIGGER tp_q_template_versions_immutable BEFORE UPDATE OR DELETE ON tp_q_template_versions
  FOR EACH ROW EXECUTE FUNCTION tp_q_template_versions_immutable_fn();
