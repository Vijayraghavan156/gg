-- Third-party risk (TPRM) v2, Phase 2 slice 2: the register of each client's
-- third parties, their services, and the CSV import. See
-- docs/tprm-v2-spec.md sections 4, 5 and 8.
--
-- tp_import_batches: one row per CSV preview. It holds the SHA-256 of the
-- previewed file (canonical form: BOM removed, line endings normalised to LF)
-- so the commit can refuse a file that changed after the preview, and its
-- status flips previewed -> committed exactly once, which makes a repeated
-- commit a no-op. The file itself is not stored here.
--
-- tp_third_parties: the register. The name is never the identity key
-- (duplicates are allowed; the interface warns). current_tier/tier_source
-- are set together: provisional_from_client_label (from the client's own
-- label via tp_client_settings.label_tier_map) until an assessment sets
-- assessed (slice 3). next_due_date is the reassessment due date.
--
-- tp_services: what each third party provides to the client.
--
-- Every child carries workspace_id and references its parent on
-- (workspace_id, id), so a row can never link to another client's record.
-- tp_events gains the same composite key to tp_third_parties (slice 1 left it
-- for this slice). It has no ON DELETE action: a third party with history is
-- never deleted (it is exited); deleting a whole workspace removes the events
-- first (lib/workspace-deletion.js orders by foreign keys) or, for a direct
-- workspace delete, in the same cascading statement.
-- created_by / committed_by / previewed_by carry no user foreign key, as for
-- the audit log: the record outlives the user.

CREATE TABLE IF NOT EXISTS tp_import_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  file_sha256 text NOT NULL CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
  filename text,
  row_count integer NOT NULL CHECK (row_count >= 0),
  status text NOT NULL DEFAULT 'previewed' CHECK (status IN ('previewed', 'committed')),
  previewed_by bigint,
  previewed_at timestamptz NOT NULL DEFAULT now(),
  committed_by bigint,
  committed_at timestamptz,
  imported_count integer CHECK (imported_count >= 0),
  CONSTRAINT tp_import_batches_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_import_batches_committed CHECK ((status = 'committed') = (committed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_tp_import_batches_hash ON tp_import_batches (workspace_id, file_sha256);
-- The same file content is committed at most once per client.
CREATE UNIQUE INDEX IF NOT EXISTS tp_import_batches_committed_hash_key
  ON tp_import_batches (workspace_id, file_sha256) WHERE status = 'committed';

CREATE TABLE IF NOT EXISTS tp_third_parties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
  legal_name text CHECK (length(legal_name) <= 200),
  registration_number text CHECK (length(registration_number) <= 100),
  website text CHECK (length(website) <= 300),
  category text CHECK (length(category) <= 100),
  country text CHECK (length(country) <= 100),
  primary_contact_name text CHECK (length(primary_contact_name) <= 200),
  primary_contact_email text CHECK (length(primary_contact_email) <= 200),
  status text NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'in_use', 'exited')),
  client_label text CHECK (length(client_label) <= 100),
  last_assessment_date date,
  current_tier text CHECK (current_tier IN ('critical', 'high', 'medium', 'low')),
  tier_source text CHECK (tier_source IN ('provisional_from_client_label', 'assessed')),
  next_due_date date,
  client_designated_critical boolean NOT NULL DEFAULT false,
  import_batch_id bigint,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_third_parties_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_third_parties_tier_pair CHECK ((current_tier IS NULL) = (tier_source IS NULL)),
  CONSTRAINT tp_third_parties_import_batch_fk FOREIGN KEY (workspace_id, import_batch_id)
    REFERENCES tp_import_batches (workspace_id, id)
);
CREATE INDEX IF NOT EXISTS idx_tp_third_parties_register ON tp_third_parties (workspace_id, status, next_due_date);
CREATE INDEX IF NOT EXISTS idx_tp_third_parties_name ON tp_third_parties (workspace_id, lower(btrim(name)));
CREATE INDEX IF NOT EXISTS idx_tp_third_parties_batch ON tp_third_parties (workspace_id, import_batch_id) WHERE import_batch_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS tp_services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  third_party_id bigint NOT NULL,
  description text NOT NULL CHECK (length(btrim(description)) BETWEEN 1 AND 2000),
  data_access text CHECK (length(data_access) <= 2000),
  hosting_countries text CHECK (length(hosting_countries) <= 500),
  contract_start date,
  contract_end date,
  notice_period_days integer CHECK (notice_period_days BETWEEN 0 AND 3650),
  annual_spend numeric(16,2) CHECK (annual_spend >= 0),
  sole_source boolean NOT NULL DEFAULT false,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_services_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_services_contract_dates CHECK (contract_end IS NULL OR contract_start IS NULL OR contract_end >= contract_start),
  CONSTRAINT tp_services_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
    REFERENCES tp_third_parties (workspace_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_tp_services_third_party ON tp_services (workspace_id, third_party_id);

-- tp_events -> tp_third_parties. Validated straight away when every existing
-- event points at a real third party (always true on a fresh install); left
-- NOT VALID (still enforced for every new event) if older rows do not, so a
-- database carrying pre-register test events still boots.
DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tp_events_third_party_fk') THEN
    ALTER TABLE tp_events ADD CONSTRAINT tp_events_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
      REFERENCES tp_third_parties (workspace_id, id) NOT VALID;
    IF NOT EXISTS (
      SELECT 1 FROM tp_events e
       WHERE e.third_party_id IS NOT NULL
         AND NOT EXISTS (SELECT 1 FROM tp_third_parties t WHERE t.workspace_id = e.workspace_id AND t.id = e.third_party_id)
    ) THEN
      ALTER TABLE tp_events VALIDATE CONSTRAINT tp_events_third_party_fk;
    ELSE
      RAISE NOTICE 'tp_events_third_party_fk left NOT VALID: older events reference third parties that do not exist';
    END IF;
  END IF;
END
$do$;
