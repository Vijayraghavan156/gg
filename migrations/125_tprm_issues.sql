CREATE TABLE IF NOT EXISTS tp_issues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  finding_id bigint NOT NULL,
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 4000),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'proposed', 'agreed', 'withdrawn')),
  agreed_fix text CHECK (length(agreed_fix) <= 2000),
  agreed_date date,
  agreed_by bigint,
  agreed_at timestamptz,
  shared_by bigint NOT NULL,
  shared_at timestamptz NOT NULL DEFAULT now(),
  withdrawn_by bigint,
  withdrawn_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_issues_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_issues_one_per_finding UNIQUE (workspace_id, finding_id),
  CONSTRAINT tp_issues_finding_fk FOREIGN KEY (workspace_id, assessment_id, finding_id)
    REFERENCES tp_findings (workspace_id, assessment_id, id) ON DELETE CASCADE,
  CONSTRAINT tp_issues_agreed CHECK ((status = 'agreed') = (agreed_at IS NOT NULL AND agreed_fix IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_tp_issues_assessment ON tp_issues (workspace_id, assessment_id, id);

CREATE TABLE IF NOT EXISTS tp_issue_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  issue_id bigint NOT NULL,
  author_kind text NOT NULL CHECK (author_kind IN ('firm', 'third_party')),
  author_user_id bigint,
  author_request_id bigint,
  author_name text CHECK (length(author_name) <= 200),
  body text CHECK (length(body) <= 4000),
  proposed_fix text CHECK (length(proposed_fix) <= 2000),
  proposed_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_issue_messages_content CHECK (length(btrim(coalesce(body, ''))) > 0 OR length(btrim(coalesce(proposed_fix, ''))) > 0),
  CONSTRAINT tp_issue_messages_issue_fk FOREIGN KEY (workspace_id, issue_id) REFERENCES tp_issues (workspace_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_tp_issue_messages_issue ON tp_issue_messages (workspace_id, issue_id, id);
