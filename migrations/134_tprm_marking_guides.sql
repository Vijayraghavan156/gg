CREATE TABLE IF NOT EXISTS tp_marking_guides (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  question_id text NOT NULL CHECK (question_id ~ '^[A-Z]{2,6}-[0-9]{1,4}$'),
  satisfactory text CHECK (length(satisfactory) <= 1500),
  partly text CHECK (length(partly) <= 1500),
  red_flags text CHECK (length(red_flags) <= 1500),
  updated_by bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_marking_guides_one_per_question UNIQUE (firm_id, question_id)
);
