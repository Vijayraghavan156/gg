ALTER TABLE tp_email_templates ADD COLUMN IF NOT EXISTS format text NOT NULL DEFAULT 'plain';
DO $do$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tp_email_templates_format') THEN
    ALTER TABLE tp_email_templates ADD CONSTRAINT tp_email_templates_format CHECK (format IN ('plain', 'rich'));
  END IF;
END $do$;

CREATE TABLE IF NOT EXISTS tp_email_template_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind ~ '^[a-z0-9_]{3,60}$'),
  subject text CHECK (length(subject) <= 200),
  headline text CHECK (length(headline) <= 200),
  opening text CHECK (length(opening) <= 2000),
  closing text CHECK (length(closing) <= 2000),
  format text NOT NULL DEFAULT 'plain' CHECK (format IN ('plain', 'rich')),
  is_standard boolean NOT NULL DEFAULT false,
  saved_by bigint,
  saved_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_tp_email_template_versions_kind ON tp_email_template_versions (firm_id, kind, id DESC);

INSERT INTO tp_email_template_versions (firm_id, kind, subject, headline, opening, closing, format, is_standard, saved_by, saved_at)
SELECT t.firm_id, t.kind, t.subject, t.headline, t.opening, t.closing, t.format, false, t.updated_by, t.updated_at
FROM tp_email_templates t
WHERE t.kind NOT LIKE 'consultant\_%'
  AND NOT EXISTS (SELECT 1 FROM tp_email_template_versions v WHERE v.firm_id = t.firm_id AND v.kind = t.kind);
