-- Third-party risk (TPRM) v2, Phase 2 slice 3a: the firm's criticality model.
-- See docs/tprm-v2-spec.md sections 4 and 5.
--
-- tp_criticality_models: one row per version of a firm's model. questions is
-- a JSON array of pick-one questions:
--   { "id", "kind": "criticality" | "service_description", "text",
--     "answers": [ { "id", "label", "tier": "Low" | "Medium" | "High" | "Critical" } ] }
-- The tier of a third party is the most serious tier among its answers
-- ("highest answer wins"). The interval columns are the firm's default
-- reassessment intervals (months) per tier; tp_client_settings can override
-- them per client.
--
-- Lifecycle: draft -> active -> retired. A firm has at most one active and at
-- most one draft version. Only a draft can be edited or discarded. The guard
-- trigger lets an active version change only into retired (nothing else on
-- the row may change) and rejects every change to a retired version, and
-- deleting an active or retired version. Deleting a whole firm goes through
-- lib/workspace-deletion.js, which suspends the guard; the guard also lets a
-- cascaded delete through once the firm row itself is gone. The detailed
-- content rules (unique ids, two answers per question, service-description
-- answers are Low, ...) live in lib/tprm/criticality.js, which every save and
-- activation goes through; the database enforces the shape and the tiers.
--
-- Every firm gets the starter model (spec section 5) as version 1, active:
-- existing firms by the backfill below, new firms by an AFTER INSERT trigger
-- on firms (firms are created by raw SQL in several places). The starter
-- questions are also defined in lib/tprm/criticality.js (STARTER_QUESTIONS);
-- a test keeps the two identical.
--
-- created_by / activated_by / retired_by carry no foreign key, as for the
-- audit log (migration 086): the record outlives the user. (firm_id, id) is
-- unique so assessments (slice 3b) can reference a version with a composite key.

CREATE OR REPLACE FUNCTION tp_criticality_questions_ok(q jsonb) RETURNS boolean
LANGUAGE sql IMMUTABLE
AS $fn$
  SELECT jsonb_typeof(q) = 'array'
     AND jsonb_array_length(q) > 0
     AND NOT EXISTS (
       SELECT 1 FROM jsonb_array_elements(q) item
        WHERE jsonb_typeof(item) <> 'object'
           OR COALESCE(item->>'kind', '') NOT IN ('criticality', 'service_description')
           OR jsonb_typeof(item->'answers') IS DISTINCT FROM 'array'
           OR jsonb_array_length(item->'answers') < 2
           OR EXISTS (
             SELECT 1 FROM jsonb_array_elements(item->'answers') a
              WHERE jsonb_typeof(a) <> 'object'
                 OR COALESCE(a->>'tier', '') NOT IN ('Low', 'Medium', 'High', 'Critical')
                 OR (item->>'kind' = 'service_description' AND a->>'tier' IS DISTINCT FROM 'Low')
           )
     )
     AND EXISTS (SELECT 1 FROM jsonb_array_elements(q) item WHERE item->>'kind' = 'criticality');
$fn$;

CREATE TABLE IF NOT EXISTS tp_criticality_models (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  version integer NOT NULL CHECK (version >= 1),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'retired')),
  questions jsonb NOT NULL CHECK (tp_criticality_questions_ok(questions)),
  interval_months_critical integer NOT NULL DEFAULT 12 CHECK (interval_months_critical BETWEEN 1 AND 120),
  interval_months_high integer NOT NULL DEFAULT 12 CHECK (interval_months_high BETWEEN 1 AND 120),
  interval_months_medium integer NOT NULL DEFAULT 24 CHECK (interval_months_medium BETWEEN 1 AND 120),
  interval_months_low integer NOT NULL DEFAULT 36 CHECK (interval_months_low BETWEEN 1 AND 120),
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  activated_by bigint,
  activated_at timestamptz,
  retired_by bigint,
  retired_at timestamptz,
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_criticality_models_firm_id_id_key UNIQUE (firm_id, id),
  CONSTRAINT tp_criticality_models_firm_version_key UNIQUE (firm_id, version),
  CONSTRAINT tp_criticality_models_activation CHECK (status = 'draft' OR activated_at IS NOT NULL),
  CONSTRAINT tp_criticality_models_retirement CHECK (status <> 'retired' OR retired_at IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS tp_criticality_models_one_active ON tp_criticality_models (firm_id) WHERE status = 'active';
CREATE UNIQUE INDEX IF NOT EXISTS tp_criticality_models_one_draft ON tp_criticality_models (firm_id) WHERE status = 'draft';

CREATE OR REPLACE FUNCTION tp_criticality_models_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status = 'draft' OR NOT EXISTS (SELECT 1 FROM firms WHERE id = OLD.firm_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_criticality_models: an ' || OLD.status || ' version cannot be deleted';
  END IF;
  IF NEW.firm_id IS DISTINCT FROM OLD.firm_id OR NEW.version IS DISTINCT FROM OLD.version
     OR NEW.created_by IS DISTINCT FROM OLD.created_by OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_criticality_models: firm, version and creator cannot change';
  END IF;
  IF OLD.status = 'draft' THEN
    IF NEW.status = 'retired' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_criticality_models: a draft can only be activated, not retired';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.status = 'active' AND NEW.status = 'retired'
     AND NEW.questions = OLD.questions
     AND NEW.interval_months_critical = OLD.interval_months_critical
     AND NEW.interval_months_high = OLD.interval_months_high
     AND NEW.interval_months_medium = OLD.interval_months_medium
     AND NEW.interval_months_low = OLD.interval_months_low
     AND NEW.activated_by IS NOT DISTINCT FROM OLD.activated_by
     AND NEW.activated_at IS NOT DISTINCT FROM OLD.activated_at THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
    MESSAGE = 'tp_criticality_models: an ' || OLD.status || ' version is immutable (only a draft can be edited)';
END;
$fn$;
DROP TRIGGER IF EXISTS tp_criticality_models_guard ON tp_criticality_models;
CREATE TRIGGER tp_criticality_models_guard BEFORE UPDATE OR DELETE ON tp_criticality_models
  FOR EACH ROW EXECUTE FUNCTION tp_criticality_models_guard_fn();

