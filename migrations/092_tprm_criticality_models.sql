CREATE OR REPLACE FUNCTION tp_firms_seed_criticality_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  PERFORM tp_seed_starter_criticality_model(NEW.id);
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_firms_seed_criticality ON firms;
CREATE TRIGGER tp_firms_seed_criticality AFTER INSERT ON firms
  FOR EACH ROW EXECUTE FUNCTION tp_firms_seed_criticality_fn();

SELECT tp_seed_starter_criticality_model(id) FROM firms;
