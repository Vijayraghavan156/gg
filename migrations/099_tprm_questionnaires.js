'use strict';

// Third-party risk (TPRM) v2, Phase 3 part A: the question bank, a
// questionnaire per assessment, and secure links for the third party. See
// docs/tprm-v2-spec.md section 4b. Migrations 083-098 are applied and frozen;
// this one only adds objects (and one new trigger on tp_assessments).
//
// tp_question_bank_versions: the approved question bank, global (one bank for
// every firm). Each version is the whole of data/tprm-question-bank.json as
// published, with the sha256 of the file. Immutable once published: the
// guard rejects update, delete and truncate. This migration publishes version
// 1 from the file as it is now; a later bank is published by a later
// migration as version 2, and questionnaires keep the version they pinned.
//
// tp_questionnaires: one per assessment. Pins the bank version, and records
// the tier and delivery model it was assembled for, the modules (added by the
// mapping table or by hand, removed by hand: who, when and why), which modules
// may be added while the third party answers (dynamic_modules), the ordered
// question ids grouped by domain and module (sections) and the rows the
// consultant checks instead of the third party (consultant_check_ids).
// Prepared only once the tier is confirmed and while the assessment is not
// frozen (tier_confirmed, recommendation_draft; spec 2a item 9). Its content
// changes only while it is a draft and the assessment is not frozen; status
// moves forward (draft -> sent -> in_progress -> submitted -> under_review ->
// closed, closed from any status) and never back to draft.
//
// tp_vendor_requests: a link for the third party to answer the
// questionnaire. Only the sha256 of the token is stored (the token is 32
// random bytes, shown once to the consultant). At most one active link per
// questionnaire (partial unique index): issuing a new one revokes the old one
// in the same transaction. Expiry is expires_at, read at request time (no
// stored "expired" status; opening a link changes nothing). submitted is
// reserved for part B (the third party submitted: the link is used up).
// last_opened_at is written only by an explicit action (part B), never by
// opening the link. An assessment is cancelled only with no active link left
// (the domain revokes them in the cancel transaction; the trigger below holds
// the rule).
//
// Like the other TPRM guards, a delete passes once the workspace row itself
// is gone (a direct workspace delete cascades), and lib/workspace-deletion.js
// suspends the guards when it purges a client. User columns carry no foreign
// key, as for the audit log (migration 086): the record outlives the user.

