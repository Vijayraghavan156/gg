CREATE TABLE IF NOT EXISTS tp_client_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'accepted', 'declined', 'withdrawn')),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
  legal_name text CHECK (length(legal_name) <= 200),
  website text CHECK (length(website) <= 300),
  country text CHECK (length(country) <= 100),
  contact_name text CHECK (length(contact_name) <= 200),
  contact_email text CHECK (length(contact_email) <= 200),
  service_description text NOT NULL CHECK (length(btrim(service_description)) BETWEEN 1 AND 2000),
  business_unit text CHECK (length(business_unit) <= 100),
  service_volume text CHECK (length(service_volume) <= 200),
  owner_user_id bigint,
  planned_start date,
  notes text CHECK (length(notes) <= 2000),
  criticality_model_id bigint,
  answers jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(answers) = 'object'),
  requested_by bigint NOT NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  decided_by bigint,
  decided_at timestamptz,
  decline_reason text CHECK (length(decline_reason) <= 1000),
  third_party_id bigint,
  answers_used_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_client_requests_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_client_requests_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
    REFERENCES tp_third_parties (workspace_id, id) ON DELETE SET NULL (third_party_id),
  CONSTRAINT tp_client_requests_link CHECK (status = 'accepted' OR third_party_id IS NULL),
  CONSTRAINT tp_client_requests_accepted CHECK (status <> 'accepted' OR decided_at IS NOT NULL),
  CONSTRAINT tp_client_requests_declined CHECK (status <> 'declined' OR (decided_at IS NOT NULL AND length(btrim(coalesce(decline_reason, ''))) > 0))
);
CREATE INDEX IF NOT EXISTS idx_tp_client_requests_ws ON tp_client_requests (workspace_id, status, requested_at DESC);
