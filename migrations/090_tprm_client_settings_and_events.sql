-- Third-party risk (TPRM) v2, Phase 2 slice 1: the per-client switch and the
-- append-only event chain. See docs/tprm-v2-spec.md sections 2 and 4.
--
-- tp_client_settings: one row per client workspace. enabled switches the
-- third-party risk service on for that client; the interval columns (months)
-- override the firm's criticality-model defaults per tier when set; and
-- label_tier_map maps the client's own criticality labels to a tier
-- (used by the slice 2 import).
--
-- tp_events: every TPRM state change. One hash chain per assessment plus one
-- per third party (chain_type + chain_id). The BEFORE INSERT trigger numbers
-- the event within its chain, rejects a fork (prev_hash must equal the latest
-- hash of that chain, or 64 zeros for the first event) and computes the hash
-- itself with tp_event_hash(), which the verifier tp_verify_event_chains()
-- also uses. A unique index on (chain, prev_hash) makes a fork impossible even
-- if two writers race. UPDATE, DELETE and TRUNCATE are rejected; deleting a
-- whole client workspace goes through lib/workspace-deletion.js, which
-- suspends the guard, and the guard also lets a cascaded delete through once
-- the workspace row itself is gone.
--
-- The composite foreign keys (workspace_id, third_party_id) and
-- (workspace_id, assessment_id) are added by the slices that create
-- tp_third_parties and tp_assessments. actor_user_id and enabled_by carry no
-- foreign key, as for the audit log (migration 086): the record outlives the
-- user.

CREATE TABLE IF NOT EXISTS tp_client_settings (
  workspace_id bigint PRIMARY KEY REFERENCES workspaces(id) ON DELETE CASCADE,
  enabled boolean NOT NULL DEFAULT false,
  interval_months_critical integer CHECK (interval_months_critical BETWEEN 1 AND 120),
  interval_months_high integer CHECK (interval_months_high BETWEEN 1 AND 120),
  interval_months_medium integer CHECK (interval_months_medium BETWEEN 1 AND 120),
  interval_months_low integer CHECK (interval_months_low BETWEEN 1 AND 120),
  label_tier_map jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(label_tier_map) = 'object'),
  enabled_at timestamptz,
  enabled_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1)
);
CREATE INDEX IF NOT EXISTS idx_tp_client_settings_enabled ON tp_client_settings (workspace_id) WHERE enabled;

CREATE TABLE IF NOT EXISTS tp_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  chain_type text NOT NULL CHECK (chain_type IN ('assessment', 'third_party')),
  chain_id bigint NOT NULL,
  chain_seq integer NOT NULL,
  third_party_id bigint,
  assessment_id bigint,
  actor_user_id bigint,
  action text NOT NULL CHECK (action ~ '^[a-z][a-z0-9_.]{0,79}$'),
  before_state jsonb,
  after_state jsonb,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  prev_hash text NOT NULL CHECK (prev_hash ~ '^[0-9a-f]{64}$'),
  hash text NOT NULL CHECK (hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT tp_events_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_events_chain_subject CHECK (
    (chain_type = 'assessment' AND assessment_id IS NOT NULL AND chain_id = assessment_id)
    OR (chain_type = 'third_party' AND assessment_id IS NULL AND third_party_id IS NOT NULL AND chain_id = third_party_id)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS tp_events_chain_seq_key ON tp_events (workspace_id, chain_type, chain_id, chain_seq);
CREATE UNIQUE INDEX IF NOT EXISTS tp_events_chain_link_key ON tp_events (workspace_id, chain_type, chain_id, prev_hash);
CREATE INDEX IF NOT EXISTS idx_tp_events_third_party ON tp_events (workspace_id, third_party_id);
CREATE INDEX IF NOT EXISTS idx_tp_events_assessment ON tp_events (workspace_id, assessment_id);

-- The canonical form of an event: a JSON array of every stored field except
-- the hash, with the timestamp rendered in UTC to microseconds. jsonb text
-- output is deterministic, so the same row always hashes the same way.
CREATE OR REPLACE FUNCTION tp_event_hash(e tp_events) RETURNS text
LANGUAGE sql STABLE
AS $fn$
  SELECT encode(sha256(convert_to(jsonb_build_array(
    e.id, e.workspace_id, e.chain_type, e.chain_id, e.chain_seq,
    e.third_party_id, e.assessment_id, e.actor_user_id, e.action,
    e.before_state, e.after_state,
    to_char(e.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
    e.prev_hash
  )::text, 'UTF8')), 'hex');
$fn$;

CREATE OR REPLACE FUNCTION tp_events_chain_insert_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  latest_hash text;
  latest_seq integer;
  computed text;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('tp_events:' || NEW.workspace_id || ':' || NEW.chain_type || ':' || NEW.chain_id));
  SELECT e.hash, e.chain_seq INTO latest_hash, latest_seq
    FROM tp_events e
   WHERE e.workspace_id = NEW.workspace_id AND e.chain_type = NEW.chain_type AND e.chain_id = NEW.chain_id
   ORDER BY e.chain_seq DESC
   LIMIT 1;
  IF NEW.prev_hash IS DISTINCT FROM COALESCE(latest_hash, repeat('0', 64)) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_events chain fork rejected: prev_hash does not match the latest hash of this chain';
  END IF;
  NEW.chain_seq := COALESCE(latest_seq, 0) + 1;
  computed := tp_event_hash(NEW);
  IF NEW.hash IS NOT NULL AND NEW.hash <> computed THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_events hash does not match the event content';
  END IF;
  NEW.hash := computed;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_events_chain_insert ON tp_events;
CREATE TRIGGER tp_events_chain_insert BEFORE INSERT ON tp_events
  FOR EACH ROW EXECUTE FUNCTION tp_events_chain_insert_fn();

CREATE OR REPLACE FUNCTION tp_events_append_only_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
    MESSAGE = 'tp_events is append-only (' || lower(TG_OP) || ' rejected)';
END;
$fn$;
DROP TRIGGER IF EXISTS tp_events_append_only ON tp_events;
CREATE TRIGGER tp_events_append_only BEFORE UPDATE OR DELETE ON tp_events
  FOR EACH ROW EXECUTE FUNCTION tp_events_append_only_fn();
DROP TRIGGER IF EXISTS tp_events_no_truncate ON tp_events;
CREATE TRIGGER tp_events_no_truncate BEFORE TRUNCATE ON tp_events
  FOR EACH STATEMENT EXECUTE FUNCTION tp_events_append_only_fn();

-- Recomputes every chain (or one workspace's chains) and returns the first
-- broken event of each broken chain: a gap in the numbering, a prev_hash that
-- does not match the previous event, or content that no longer matches its hash.
CREATE OR REPLACE FUNCTION tp_verify_event_chains(p_workspace_id bigint DEFAULT NULL)
RETURNS TABLE (broken_workspace_id bigint, broken_chain_type text, broken_chain_id bigint,
               event_id bigint, event_seq integer, problem text)
LANGUAGE plpgsql STABLE
AS $fn$
DECLARE
  r tp_events;
  current_key text := NULL;
  expected_prev text;
  expected_seq integer;
  chain_broken boolean := false;
  found_problem text;
BEGIN
  FOR r IN
    SELECT * FROM tp_events e
     WHERE p_workspace_id IS NULL OR e.workspace_id = p_workspace_id
     ORDER BY e.workspace_id, e.chain_type, e.chain_id, e.chain_seq, e.id
  LOOP
    IF current_key IS DISTINCT FROM (r.workspace_id || ':' || r.chain_type || ':' || r.chain_id) THEN
      current_key := r.workspace_id || ':' || r.chain_type || ':' || r.chain_id;
      expected_prev := repeat('0', 64);
      expected_seq := 1;
      chain_broken := false;
    END IF;
    CONTINUE WHEN chain_broken;
    found_problem := NULL;
    IF r.chain_seq <> expected_seq THEN
      found_problem := 'sequence_gap';
    ELSIF r.prev_hash <> expected_prev THEN
      found_problem := 'broken_link';
    ELSIF r.hash <> tp_event_hash(r) THEN
      found_problem := 'hash_mismatch';
    END IF;
    IF found_problem IS NOT NULL THEN
      broken_workspace_id := r.workspace_id;
      broken_chain_type := r.chain_type;
      broken_chain_id := r.chain_id;
      event_id := r.id;
      event_seq := r.chain_seq;
      problem := found_problem;
      RETURN NEXT;
      chain_broken := true;
      CONTINUE;
    END IF;
    expected_prev := r.hash;
    expected_seq := expected_seq + 1;
  END LOOP;
END;
$fn$;
