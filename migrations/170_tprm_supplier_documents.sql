CREATE TABLE IF NOT EXISTS tp_party_documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  third_party_id bigint NOT NULL,
  kind text NOT NULL CHECK (kind IN ('iso27001_certificate', 'soc2_report', 'contract', 'dpa', 'insurance_certificate', 'policy', 'other')),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  issued_on date,
  expires_on date,
  original_name text NOT NULL,
  stored_path text NOT NULL,
  size_bytes bigint NOT NULL DEFAULT 0,
  mime_type text,
  sha256 text NOT NULL,
  shared_with_client boolean NOT NULL DEFAULT false,
  shared_by bigint,
  shared_at timestamptz,
  uploaded_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  deleted_by bigint,
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_party_documents_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_party_documents_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
    REFERENCES tp_third_parties (workspace_id, id) ON DELETE CASCADE,
  CONSTRAINT tp_party_documents_dates CHECK (issued_on IS NULL OR expires_on IS NULL OR expires_on >= issued_on)
);
CREATE INDEX IF NOT EXISTS idx_tp_party_documents_party ON tp_party_documents (workspace_id, third_party_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_tp_party_documents_expiry ON tp_party_documents (workspace_id, expires_on) WHERE deleted_at IS NULL;
