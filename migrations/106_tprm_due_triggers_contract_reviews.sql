-- Third-party risk (TPRM) v2, Phase 5B: early reassessment triggers and the
-- contract checklist of an assessment. See docs/tprm-v2-spec.md section 4e.
-- Migrations 083-104 are applied and frozen; this one only adds objects.
--
-- tp_trigger_events: a firm user recorded an event that brings a third
-- party's reassessment forward (a breach, a change of ownership, a change of
-- AI model or provider, or another reason in words). Only for a third party in
-- use. The row keeps the due date before (previous_due_date) and the due date
-- the trigger set (new_due_date: today in the client's time zone, or the
-- earlier date when the third party was already overdue). Insert-only: the
-- guard rejects update and delete, and lets a delete through once the
-- workspace row itself is gone (a direct workspace delete cascades);
-- lib/workspace-deletion.js suspends it when it purges a client. A trigger
-- is shown ("Triggered: <reason>") while the third party's next due date
-- still equals new_due_date; the next client decision moves the date on.
--
-- tp_contract_reviews: the firm's review of the third party's contract
-- against the question bank's contract checklist, one row per clause, per
-- assessment. Created on demand (the consultant starts the checklist) from
-- the pinned bank version (the questionnaire's, or the latest when the
-- assessment has none); every row of an assessment pins the same version, and
-- the clause id must exist in that version's contract_checklist (trigger).
-- applies_to, conditional and module are copied from the clause so a rulebook
-- filter (Phase 6) can select rows without reading the bank. Status
-- not_reviewed / present_satisfactory / present_gap / missing / not_required,
-- the contract reference, the reviewer's comment and an optional finding of
-- the same assessment (composite key carrying assessment_id; removing the
-- finding clears the link only, ON DELETE SET NULL (finding_id)). Firm-only:
-- never sent to the third party and never shown in the client portal.
-- Freeze (spec 2a item 9): rows are created, changed and removed only while
-- the assessment is open and not frozen, as for findings; the guard holds the
-- same rule and lets changes through once the workspace row is gone.
--
-- User columns carry no foreign key, as for the audit log (migration 086).

CREATE TABLE IF NOT EXISTS tp_trigger_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  third_party_id bigint NOT NULL,
  reason text NOT NULL CHECK (reason IN ('breach', 'ownership_change', 'ai_change', 'other')),
  details text CHECK (length(details) <= 1000),
  previous_due_date date,
  new_due_date date NOT NULL,
  recorded_by bigint NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_trigger_events_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_trigger_events_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
    REFERENCES tp_third_parties (workspace_id, id),
  CONSTRAINT tp_trigger_events_other_details CHECK (reason <> 'other' OR length(btrim(coalesce(details, ''))) >= 1),
  CONSTRAINT tp_trigger_events_not_later CHECK (previous_due_date IS NULL OR new_due_date <= previous_due_date)
);
CREATE INDEX IF NOT EXISTS idx_tp_trigger_events_third_party ON tp_trigger_events (workspace_id, third_party_id, id);

CREATE OR REPLACE FUNCTION tp_trigger_events_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_trigger_events: a recorded trigger event is never deleted';
  END IF;
  IF TG_OP IN ('UPDATE', 'TRUNCATE') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_trigger_events: a recorded trigger event never changes (' || lower(TG_OP) || ' rejected)';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM tp_third_parties
     WHERE workspace_id = NEW.workspace_id AND id = NEW.third_party_id AND status = 'in_use') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_trigger_events: an early reassessment is triggered only for a third party in use';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_trigger_events_guard ON tp_trigger_events;
CREATE TRIGGER tp_trigger_events_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_trigger_events
  FOR EACH ROW EXECUTE FUNCTION tp_trigger_events_guard_fn();
DROP TRIGGER IF EXISTS tp_trigger_events_no_truncate ON tp_trigger_events;
CREATE TRIGGER tp_trigger_events_no_truncate BEFORE TRUNCATE ON tp_trigger_events
  FOR EACH STATEMENT EXECUTE FUNCTION tp_trigger_events_guard_fn();

CREATE TABLE IF NOT EXISTS tp_contract_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  bank_version_id bigint NOT NULL,
  bank_version integer NOT NULL,
  clause_id text NOT NULL CHECK (clause_id ~ '^[A-Za-z0-9_.-]{1,40}$'),
  position integer NOT NULL CHECK (position >= 0),
  applies_to text NOT NULL CHECK (length(btrim(applies_to)) BETWEEN 1 AND 200),
  conditional boolean NOT NULL DEFAULT false,
  module text CHECK (length(module) <= 200),
  status text NOT NULL DEFAULT 'not_reviewed'
    CHECK (status IN ('not_reviewed', 'present_satisfactory', 'present_gap', 'missing', 'not_required')),
  contract_reference text CHECK (length(contract_reference) <= 300),
  comment text CHECK (length(comment) <= 2000),
  finding_id bigint,
  reviewed_by bigint,
  reviewed_at timestamptz,
  created_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_contract_reviews_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_contract_reviews_clause_key UNIQUE (workspace_id, assessment_id, clause_id),
  CONSTRAINT tp_contract_reviews_assessment_fk FOREIGN KEY (workspace_id, assessment_id)
    REFERENCES tp_assessments (workspace_id, id),
  CONSTRAINT tp_contract_reviews_bank_fk FOREIGN KEY (bank_version_id, bank_version)
    REFERENCES tp_question_bank_versions (id, version),
  CONSTRAINT tp_contract_reviews_finding_fk FOREIGN KEY (workspace_id, assessment_id, finding_id)
    REFERENCES tp_findings (workspace_id, assessment_id, id) ON DELETE SET NULL (finding_id),
  CONSTRAINT tp_contract_reviews_conditional_module CHECK (NOT conditional OR module IS NOT NULL),
  CONSTRAINT tp_contract_reviews_reviewed CHECK (
    (status = 'not_reviewed') OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_tp_contract_reviews_assessment ON tp_contract_reviews (workspace_id, assessment_id, position);
CREATE INDEX IF NOT EXISTS idx_tp_contract_reviews_finding ON tp_contract_reviews (workspace_id, finding_id) WHERE finding_id IS NOT NULL;

CREATE OR REPLACE FUNCTION tp_contract_reviews_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  ws bigint;
  aid bigint;
  st text;
  pinned bigint;
BEGIN
  IF TG_OP = 'DELETE' THEN
    ws := OLD.workspace_id; aid := OLD.assessment_id;
  ELSE
    ws := NEW.workspace_id; aid := NEW.assessment_id;
  END IF;
  -- A whole-workspace delete: the cascade (and the finding link it clears)
  -- goes through once the workspace row is gone.
  IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = ws) THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;
  st := tp_assessment_status_of(ws, aid);
  IF st IS NULL OR st IN ('recommendation_in_review', 'recommendation_issued', 'information_requested', 'completed', 'cancelled') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_contract_reviews: the contract checklist is frozen while the assessment is ' || coalesce(st, 'missing')
        || ' (' || lower(TG_OP) || ' rejected)';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  IF TG_OP = 'UPDATE' AND ROW(NEW.id, NEW.workspace_id, NEW.assessment_id, NEW.bank_version_id, NEW.bank_version, NEW.clause_id,
         NEW.position, NEW.applies_to, NEW.conditional, NEW.module, NEW.created_by, NEW.created_at)
     IS DISTINCT FROM ROW(OLD.id, OLD.workspace_id, OLD.assessment_id, OLD.bank_version_id, OLD.bank_version, OLD.clause_id,
         OLD.position, OLD.applies_to, OLD.conditional, OLD.module, OLD.created_by, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_contract_reviews: the clause a row reviews never changes';
  END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT bank_version_id INTO pinned FROM tp_contract_reviews
      WHERE workspace_id = NEW.workspace_id AND assessment_id = NEW.assessment_id LIMIT 1;
    IF pinned IS NOT NULL AND pinned <> NEW.bank_version_id THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_contract_reviews: every clause of an assessment comes from the same question bank version';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM tp_question_bank_versions b,
         jsonb_array_elements(CASE WHEN jsonb_typeof(b.content->'contract_checklist') = 'array'
           THEN b.content->'contract_checklist' ELSE '[]'::jsonb END) c
       WHERE b.id = NEW.bank_version_id AND c->>'id' = NEW.clause_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_contract_reviews: the clause is not in the pinned question bank version''s contract checklist';
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_contract_reviews_guard ON tp_contract_reviews;
CREATE TRIGGER tp_contract_reviews_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_contract_reviews
  FOR EACH ROW EXECUTE FUNCTION tp_contract_reviews_guard_fn();
