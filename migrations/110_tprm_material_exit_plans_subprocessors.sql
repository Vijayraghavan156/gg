-- Third-party risk (TPRM) v2, Phase 6B: the material flag, exit plans with
-- automatic client conditions, and the subprocessor list. See
-- docs/tprm-v2-spec.md section 4j. Migrations 083-109 are applied and frozen;
-- this one adds objects and columns and never replaces an earlier function.
--
-- tp_services gains the material flag (who, when and why it last changed).
-- The application shows and changes it only for a client with at least one
-- ticked rulebook (lib/tprm/exit-plans.js).
--
-- tp_exit_plans: one per service (composite keys). A checklist, not a score:
-- alternative provider, data return and deletion, time to switch (number and
-- unit) and the date it was last tested or reviewed, plus notes. status is
-- computed by the database: complete when all four are filled, else
-- incomplete. Removed with its service.
--
-- tp_conditions gains automatic and auto_service_id: the condition the
-- application adds to a draft recommendation for a material service in scope
-- that has no complete exit plan, when the assessment's rulebooks require
-- exit plans (the questionnaire's pins, else the client's ticks now: the 4i
-- rule). Owned by the client. No foreign key to tp_services: an issued
-- condition outlives a removed service. The service never changes, nor (for an
-- automatic one) the description or owner; the due date stays editable while
-- the recommendation is a draft (105's guard). Deleted only when no longer
-- needed (the service is not material any more, its plan is complete, it left
-- the scope, the rulebooks no longer require plans, or the outcome is a
-- reject) or after a manager's override.
--
-- tp_exit_plan_overrides: a manager's removal of an automatic condition from
-- one recommendation version, with a reason. Inserted only while that version
-- is a draft (or changes requested), by a manager of the firm; never changed
-- or deleted (except with the workspace).
--
-- tp_exit_plan_needed(workspace, assessment): the services that need an
-- automatic condition. Read by the application too, so the rule lives once.
-- A recommendation moves to in review or issued only when (a) an "approve"
-- outcome has no such service left (after overrides) and (b) an "approve with
-- conditions" outcome carries an automatic condition (or an override) for each
-- of them. A reject (Do not onboard / Exit) raises none.
--
-- tp_subprocessors: the third party's own vendors (fourth parties), entered
-- by the firm: name, what they do, country, source (questionnaire or manual)
-- and the third party's submitted answer it was copied from (an answer of
-- that third party's own assessments, checked by the trigger).
--
-- Guards let a whole-workspace delete through, as the other TPRM guards do
-- (lib/workspace-deletion.js suspends them; a direct workspace delete
-- cascades). User columns carry no foreign key (migration 086).

