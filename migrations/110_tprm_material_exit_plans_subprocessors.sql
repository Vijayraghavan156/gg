-- ---- exit plans ----------------------------------------------------------------

CREATE TABLE IF NOT EXISTS tp_exit_plans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  third_party_id bigint NOT NULL,
  service_id bigint NOT NULL,
  alternative_provider text CHECK (length(alternative_provider) <= 2000),
  data_return text CHECK (length(data_return) <= 4000),
  switch_time integer CHECK (switch_time BETWEEN 1 AND 3650),
  switch_unit text CHECK (switch_unit IN ('days', 'weeks', 'months')),
  last_tested_on date,
  notes text CHECK (length(notes) <= 4000),
  status text GENERATED ALWAYS AS (
    CASE WHEN length(btrim(COALESCE(alternative_provider, ''))) > 0
          AND length(btrim(COALESCE(data_return, ''))) > 0
          AND switch_time IS NOT NULL AND switch_unit IS NOT NULL
          AND last_tested_on IS NOT NULL
      THEN 'complete' ELSE 'incomplete' END) STORED,
  created_by bigint,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_exit_plans_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_exit_plans_one_per_service UNIQUE (workspace_id, service_id),
  CONSTRAINT tp_exit_plans_switch_pair CHECK ((switch_time IS NULL) = (switch_unit IS NULL)),
  CONSTRAINT tp_exit_plans_service_fk FOREIGN KEY (workspace_id, third_party_id, service_id)
    REFERENCES tp_services (workspace_id, third_party_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_tp_exit_plans_third_party ON tp_exit_plans (workspace_id, third_party_id);

