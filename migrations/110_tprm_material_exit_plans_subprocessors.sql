  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  recommendation_id bigint NOT NULL,
  service_id bigint NOT NULL,
  service_description text CHECK (length(service_description) <= 2000),
  reason text NOT NULL CHECK (length(btrim(reason)) BETWEEN 1 AND 1000),
  removed_by bigint NOT NULL,
  removed_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_exit_plan_overrides_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_exit_plan_overrides_one UNIQUE (workspace_id, recommendation_id, service_id),
  CONSTRAINT tp_exit_plan_overrides_recommendation_fk FOREIGN KEY (workspace_id, recommendation_id)
    REFERENCES tp_recommendations (workspace_id, id)
);

-- Whether the assessment's rulebooks require exit plans: those pinned on its
-- questionnaire, else the client's ticked rulebooks now (active, switched on).
CREATE OR REPLACE FUNCTION tp_exit_plan_required(p_workspace_id bigint, p_assessment_id bigint) RETURNS boolean
LANGUAGE sql STABLE
AS $fn$
  SELECT CASE
    WHEN EXISTS (SELECT 1 FROM tp_questionnaires q WHERE q.workspace_id = p_workspace_id AND q.assessment_id = p_assessment_id)
    THEN EXISTS (
      SELECT 1 FROM tp_questionnaires q CROSS JOIN LATERAL jsonb_array_elements(q.rulebooks) AS e
       WHERE q.workspace_id = p_workspace_id AND q.assessment_id = p_assessment_id
         AND jsonb_typeof(e) = 'object' AND COALESCE((e->>'exit_plan_required')::boolean, false))
    ELSE EXISTS (
      SELECT 1 FROM tp_client_rulebooks c JOIN tp_rulebooks r ON r.firm_id = c.firm_id AND r.id = c.rulebook_id
       WHERE c.workspace_id = p_workspace_id AND r.status = 'active' AND r.enabled AND r.exit_plan_required)
  END
$fn$;

-- The services in the assessment's scope that are material and have no
-- complete exit plan, when its rulebooks require exit plans.
CREATE OR REPLACE FUNCTION tp_exit_plan_needed(p_workspace_id bigint, p_assessment_id bigint) RETURNS SETOF bigint
LANGUAGE sql STABLE
AS $fn$
  SELECT DISTINCT s.id FROM tp_assessments a
    CROSS JOIN LATERAL jsonb_array_elements(a.services_in_scope) AS e
    JOIN tp_services s ON s.workspace_id = a.workspace_id AND s.third_party_id = a.third_party_id AND s.id::text = e->>'id'
   WHERE a.workspace_id = p_workspace_id AND a.id = p_assessment_id AND s.material
     AND tp_exit_plan_required(p_workspace_id, p_assessment_id)
     AND NOT EXISTS (SELECT 1 FROM tp_exit_plans x
       WHERE x.workspace_id = s.workspace_id AND x.service_id = s.id AND x.status = 'complete')
$fn$;

-- A recommendation goes to review or is issued only with the exit plan rule met.
CREATE OR REPLACE FUNCTION tp_recommendations_exit_plans_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  n_needed integer;
  n_missing integer;
BEGIN
  IF NEW.status NOT IN ('in_review', 'issued') OR NEW.status IS NOT DISTINCT FROM OLD.status
     OR NEW.outcome IS NULL OR NEW.outcome = 'reject' THEN
    RETURN NEW;
  END IF;
  SELECT count(*),
         count(*) FILTER (WHERE NOT EXISTS (SELECT 1 FROM tp_conditions c
           WHERE c.workspace_id = NEW.workspace_id AND c.recommendation_id = NEW.id AND c.automatic AND c.auto_service_id = n.sid))
    INTO n_needed, n_missing
    FROM tp_exit_plan_needed(NEW.workspace_id, NEW.assessment_id) AS n(sid)
   WHERE NOT EXISTS (SELECT 1 FROM tp_exit_plan_overrides o
     WHERE o.workspace_id = NEW.workspace_id AND o.recommendation_id = NEW.id AND o.service_id = n.sid);
  IF NEW.outcome = 'approve' AND n_needed > 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendations: a material service without a complete exit plan needs the "with conditions" outcome';
  END IF;
  IF NEW.outcome = 'approve_with_conditions' AND n_missing > 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendations: every material service without a complete exit plan needs its automatic condition';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_recommendations_exit_plans ON tp_recommendations;
CREATE TRIGGER tp_recommendations_exit_plans BEFORE UPDATE OF status ON tp_recommendations
  FOR EACH ROW EXECUTE FUNCTION tp_recommendations_exit_plans_fn();

-- Automatic conditions: their service never changes, nor their description or
-- owner; inserted only for a service that needs one (no override); deleted
-- only when no longer needed, on a reject outcome, or after an override.
-- 105's tp_conditions_guard still decides when a condition can change at all.
CREATE OR REPLACE FUNCTION tp_conditions_automatic_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  rec record;
  row_ record;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF NOT OLD.automatic OR NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    row_ := OLD;
  ELSE
    row_ := NEW;
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF NEW.automatic IS DISTINCT FROM OLD.automatic OR NEW.auto_service_id IS DISTINCT FROM OLD.auto_service_id THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: whether a condition is automatic, and its service, never change';
    END IF;
    IF NOT NEW.automatic THEN RETURN NEW; END IF;
    IF NEW.description IS DISTINCT FROM OLD.description OR NEW.owner IS DISTINCT FROM OLD.owner THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: the description and owner of an automatic condition never change';
    END IF;
    RETURN NEW;
  END IF;
  IF TG_OP = 'INSERT' AND NOT NEW.automatic THEN RETURN NEW; END IF;
  SELECT r.id, r.assessment_id, r.outcome INTO rec FROM tp_recommendations r
   WHERE r.workspace_id = row_.workspace_id AND r.id = row_.recommendation_id;
  IF TG_OP = 'INSERT' THEN
    IF rec.outcome = 'reject'
       OR NOT EXISTS (SELECT 1 FROM tp_exit_plan_needed(row_.workspace_id, rec.assessment_id) AS n(sid) WHERE n.sid = row_.auto_service_id)
       OR EXISTS (SELECT 1 FROM tp_exit_plan_overrides o WHERE o.workspace_id = row_.workspace_id
            AND o.recommendation_id = row_.recommendation_id AND o.service_id = row_.auto_service_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: an automatic condition is only for a material service in scope without a complete exit plan';
    END IF;
    RETURN NEW;
  END IF;
  -- DELETE of an automatic condition.
  IF rec.id IS NULL OR rec.outcome = 'reject'
     OR NOT EXISTS (SELECT 1 FROM tp_exit_plan_needed(row_.workspace_id, rec.assessment_id) AS n(sid) WHERE n.sid = row_.auto_service_id)
     OR EXISTS (SELECT 1 FROM tp_exit_plan_overrides o WHERE o.workspace_id = row_.workspace_id
          AND o.recommendation_id = row_.recommendation_id AND o.service_id = row_.auto_service_id) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
    MESSAGE = 'tp_conditions: an automatic condition is removed only by a manager''s override, with a reason';
END;
$fn$;
DROP TRIGGER IF EXISTS tp_conditions_automatic ON tp_conditions;
CREATE TRIGGER tp_conditions_automatic BEFORE INSERT OR UPDATE OR DELETE ON tp_conditions
  FOR EACH ROW EXECUTE FUNCTION tp_conditions_automatic_fn();

CREATE OR REPLACE FUNCTION tp_exit_plan_overrides_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_exit_plan_overrides: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_exit_plan_overrides: an override is never deleted';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_exit_plan_overrides: an override never changes';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM tp_recommendations r WHERE r.workspace_id = NEW.workspace_id AND r.id = NEW.recommendation_id
       AND r.status IN ('draft', 'changes_requested')) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_exit_plan_overrides: an automatic condition is removed only while the recommendation is a draft';
  END IF;
  IF NOT tp_condition_firm_user(NEW.workspace_id, NEW.removed_by, true) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_exit_plan_overrides: only a manager of the firm removes an automatic condition';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_exit_plan_overrides_guard ON tp_exit_plan_overrides;
CREATE TRIGGER tp_exit_plan_overrides_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_exit_plan_overrides
  FOR EACH ROW EXECUTE FUNCTION tp_exit_plan_overrides_guard_fn();
DROP TRIGGER IF EXISTS tp_exit_plan_overrides_no_truncate ON tp_exit_plan_overrides;
CREATE TRIGGER tp_exit_plan_overrides_no_truncate BEFORE TRUNCATE ON tp_exit_plan_overrides
  FOR EACH STATEMENT EXECUTE FUNCTION tp_exit_plan_overrides_guard_fn();

-- ---- subprocessors -----------------------------------------------------------------

CREATE TABLE IF NOT EXISTS tp_subprocessors (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  third_party_id bigint NOT NULL,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
  service text CHECK (length(service) <= 1000),
  country text CHECK (length(country) <= 100),
  source text NOT NULL CHECK (source IN ('questionnaire', 'manual')),
  answer_id bigint,
  created_by bigint,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_subprocessors_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_subprocessors_source_answer CHECK ((source = 'questionnaire') = (answer_id IS NOT NULL)),
  CONSTRAINT tp_subprocessors_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
    REFERENCES tp_third_parties (workspace_id, id) ON DELETE CASCADE,
  CONSTRAINT tp_subprocessors_answer_fk FOREIGN KEY (workspace_id, answer_id)
    REFERENCES tp_answers (workspace_id, id)
);
CREATE INDEX IF NOT EXISTS idx_tp_subprocessors_third_party ON tp_subprocessors (workspace_id, third_party_id, id);
CREATE INDEX IF NOT EXISTS idx_tp_subprocessors_name ON tp_subprocessors (workspace_id, lower(btrim(name)));

-- A subprocessor stays with its third party; an answer it was copied from is a
-- submitted answer of that third party's own assessments.
CREATE OR REPLACE FUNCTION tp_subprocessors_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'UPDATE' AND (NEW.workspace_id IS DISTINCT FROM OLD.workspace_id OR NEW.third_party_id IS DISTINCT FROM OLD.third_party_id) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_subprocessors: a subprocessor never moves to another third party';
  END IF;
  IF NEW.answer_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM tp_answers an JOIN tp_assessments a ON a.workspace_id = an.workspace_id AND a.id = an.assessment_id
        WHERE an.workspace_id = NEW.workspace_id AND an.id = NEW.answer_id AND a.third_party_id = NEW.third_party_id
          AND an.submitted_at IS NOT NULL) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_subprocessors: the answer must be a submitted answer of this third party';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_subprocessors_guard ON tp_subprocessors;
CREATE TRIGGER tp_subprocessors_guard BEFORE INSERT OR UPDATE ON tp_subprocessors
  FOR EACH ROW EXECUTE FUNCTION tp_subprocessors_guard_fn();
