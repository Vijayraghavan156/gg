'use strict';

// Third-party risk (TPRM) v2, Phase 6A: rulebooks for regulated clients. See
// docs/tprm-v2-spec.md section 4i. Migrations 083-107 are applied and frozen;
// this one only adds objects (and one column with its own trigger on
// tp_questionnaires).
//
// tp_rulebooks: per FIRM, one row per rulebook of the question bank (31 in
// bank version 1), seeded for every existing firm here and for every new firm
// by an AFTER INSERT trigger on firms (like migration 092's criticality
// model). Seeded from bank version 1 (tp_question_bank_versions, immutable)
// through data/tprm-rulebooks.js seedRows: the key, the bank's own entry
// (bank_entry, never changes), the question ids parsed into a list, the
// contract checklist tags, whether exit plans are required, the country data
// must stay in, the reference text and the status (active / watch / pending;
// only an active rulebook that is switched on can be ticked for a client).
// Managers change enabled, question_ids, exit_plan_required, data_country and
// reference_text; every change is the next version (version + 1, checked by
// the guard) and is copied to tp_rulebook_versions by a trigger, so every
// version is kept. A rulebook is never deleted (it is switched off instead),
// except with its firm.
//
// tp_rulebook_versions: every version of every rulebook, written only by the
// trigger (an insert must equal the rulebook's current row), never changed or
// deleted (except with its firm).
//
// tp_client_rulebooks: per workspace, the rulebooks ticked for the client,
// who ticked each and when. Ticked only when the rulebook is of the client's
// own firm, active and switched on; never changed (untick = delete).
//
// tp_questionnaires.rulebooks: the client's ticked rulebooks pinned when the
// questionnaire is prepared (rulebook, version and a snapshot of what the
// questionnaire, the contract checklist and the data-location check use).
// Each pinned version must be a version of the client's firm; the pin never
// changes afterwards (its own trigger; migration 099/100's guard is
// untouched). Questionnaires prepared before 109 have none.
//
// Guards let a whole-firm or whole-workspace delete through, as the other
// TPRM guards do. User columns carry no foreign key (migration 086).

