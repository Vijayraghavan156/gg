-- Third-party risk (TPRM) v2, Phase 4: the AI first-pass review of an
-- assessment (docs/tprm-v2-spec.md section 4d). Migrations 083-102 are
-- applied and frozen; this one adds tables, functions and triggers only and
-- replaces no function of an earlier migration.
--
-- tp_firm_settings: one row per firm (no row means the defaults). Holds the
-- firm's switch for the automatic AI review when a third party submits its
-- questionnaire (ai_review_auto, default ON: product decision). Managers
-- change it (tp.settings, lib/tprm/ai-review.js setAutoReview).
--
-- tp_ai_reviews: one row per run of the AI review on an assessment. It keeps
-- what was asked and what came back, never the vendor's text or file contents:
--   run_trigger   manual (a consultant pressed "Run AI review"; requested_by
--                 set) or on_submission (the questionnaire was submitted;
--                 requested_by NULL, questionnaire_id set).
--   status        queued -> running -> succeeded | failed, or queued -> failed
--                 (the assessment froze before the run started), or
--                 not_configured (no AI provider is set up: recorded once,
--                 final, nothing sent).
--   provider, model  as configured when the run started.
--   input_sha256  sha256 of the exact request body sent to the provider.
--   input_summary counts only (every value a number; a CHECK holds it).
--   suggestions   the validated suggestions (a JSON array, at most 50).
--   dropped_count suggestions the model returned that failed validation.
--   error         a fixed, sanitised message (never the provider's text).
-- At most one queued or running review per assessment (partial unique index).
-- A review starts only while the assessment's tier is confirmed and its
-- evidence is not frozen (tier_confirmed or recommendation_draft, spec 2a
-- item 9).
--
-- tp_ai_suggestions: one row per validated suggestion of a succeeded run,
-- written in the run's own transaction while the review is still running.
-- kind is finding (the only kind produced now) or conclusion (reserved). An
-- answer_id ties it to one of the third party's answers of this assessment
-- (composite key). status pending -> accepted | edited_accepted | rejected,
-- once; a decision records who and when; accepting records the finding it
-- created (tp_findings source ai_accepted, checked here). Removing that
-- finding later clears finding_id only (ON DELETE SET NULL (finding_id)).
-- tp_ai_suggestion_evidence: the files a suggestion cites; both keys carry
-- assessment_id, so a suggestion cites only files of its own assessment. A
-- pending AI row never blocks deleting a file: the link goes with the file.
--
-- No AI row is read by the client portal. Like the other TPRM guards, a
-- delete passes once the workspace row itself is gone, and
-- lib/workspace-deletion.js suspends the guards when it purges a client.
-- User columns carry no foreign key (the record outlives the user).

CREATE TABLE IF NOT EXISTS tp_firm_settings (
  firm_id bigint PRIMARY KEY REFERENCES firms(id) ON DELETE CASCADE,
  ai_review_auto boolean NOT NULL DEFAULT true,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1)
);

CREATE OR REPLACE FUNCTION tp_ai_counts_only(p jsonb) RETURNS boolean
LANGUAGE sql IMMUTABLE
AS $fn$
  SELECT p IS NULL OR (jsonb_typeof(p) = 'object'
    AND NOT EXISTS (SELECT 1 FROM jsonb_each(p) e WHERE jsonb_typeof(e.value) <> 'number'));
$fn$;

CREATE TABLE IF NOT EXISTS tp_ai_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  questionnaire_id bigint,
  run_trigger text NOT NULL CHECK (run_trigger IN ('manual', 'on_submission')),
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'not_configured')),
  provider text CHECK (length(provider) <= 40),
  model text CHECK (length(model) <= 200),
  input_sha256 text CHECK (input_sha256 ~ '^[0-9a-f]{64}$'),
  input_summary jsonb CHECK (tp_ai_counts_only(input_summary)),
  suggestions jsonb CHECK (suggestions IS NULL OR (jsonb_typeof(suggestions) = 'array' AND jsonb_array_length(suggestions) <= 50)),
  dropped_count integer CHECK (dropped_count >= 0),
  error text CHECK (length(error) <= 500),
  requested_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz,
  finished_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_ai_reviews_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_ai_reviews_assessment_id_key UNIQUE (workspace_id, assessment_id, id),
  CONSTRAINT tp_ai_reviews_assessment_fk FOREIGN KEY (workspace_id, assessment_id)
    REFERENCES tp_assessments (workspace_id, id),
  CONSTRAINT tp_ai_reviews_questionnaire_fk FOREIGN KEY (workspace_id, assessment_id, questionnaire_id)
    REFERENCES tp_questionnaires (workspace_id, assessment_id, id),
  CONSTRAINT tp_ai_reviews_trigger CHECK (
    (run_trigger = 'manual' AND requested_by IS NOT NULL)
    OR (run_trigger = 'on_submission' AND requested_by IS NULL AND questionnaire_id IS NOT NULL)),
  CONSTRAINT tp_ai_reviews_stage CHECK (
    (status = 'queued' AND started_at IS NULL AND finished_at IS NULL AND input_sha256 IS NULL AND suggestions IS NULL AND error IS NULL)
    OR (status = 'running' AND started_at IS NOT NULL AND finished_at IS NULL AND suggestions IS NULL AND error IS NULL)
    OR (status = 'succeeded' AND started_at IS NOT NULL AND finished_at IS NOT NULL AND input_sha256 IS NOT NULL
        AND suggestions IS NOT NULL AND dropped_count IS NOT NULL AND error IS NULL)
    OR (status = 'failed' AND finished_at IS NOT NULL AND suggestions IS NULL AND error IS NOT NULL)
    OR (status = 'not_configured' AND started_at IS NULL AND finished_at IS NOT NULL AND input_sha256 IS NULL
        AND suggestions IS NULL AND error IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS tp_ai_reviews_one_active ON tp_ai_reviews (workspace_id, assessment_id)
  WHERE status IN ('queued', 'running');
CREATE INDEX IF NOT EXISTS idx_tp_ai_reviews_queued ON tp_ai_reviews (created_at, id) WHERE status = 'queued';
CREATE INDEX IF NOT EXISTS idx_tp_ai_reviews_assessment ON tp_ai_reviews (workspace_id, assessment_id, id);

CREATE OR REPLACE FUNCTION tp_ai_reviews_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  a_status text;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_reviews: an AI review is never deleted';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.status NOT IN ('queued', 'not_configured') THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_ai_reviews: a review starts queued, or is recorded as not configured';
    END IF;
    SELECT status INTO a_status FROM tp_assessments WHERE workspace_id = NEW.workspace_id AND id = NEW.assessment_id;
    IF a_status IS NULL OR a_status NOT IN ('tier_confirmed', 'recommendation_draft') THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_ai_reviews: an AI review runs only while the tier is confirmed and the evidence is not frozen';
    END IF;
    RETURN NEW;
  END IF;
  IF ROW(NEW.id, NEW.workspace_id, NEW.assessment_id, NEW.questionnaire_id, NEW.run_trigger, NEW.requested_by, NEW.created_at)
     IS DISTINCT FROM ROW(OLD.id, OLD.workspace_id, OLD.assessment_id, OLD.questionnaire_id, OLD.run_trigger, OLD.requested_by, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_reviews: what a review is about cannot change';
  END IF;
  IF OLD.status IN ('succeeded', 'failed', 'not_configured') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_reviews: a finished review cannot change';
  END IF;
  IF NOT ((OLD.status = 'queued' AND NEW.status IN ('queued', 'running', 'failed'))
       OR (OLD.status = 'running' AND NEW.status IN ('running', 'succeeded', 'failed'))) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_reviews: a review moves queued -> running -> succeeded or failed';
  END IF;
  IF OLD.input_sha256 IS NOT NULL AND NEW.input_sha256 IS DISTINCT FROM OLD.input_sha256 THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_reviews: the input hash is set once';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_ai_reviews_guard ON tp_ai_reviews;
CREATE TRIGGER tp_ai_reviews_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_ai_reviews
  FOR EACH ROW EXECUTE FUNCTION tp_ai_reviews_guard_fn();

CREATE TABLE IF NOT EXISTS tp_ai_suggestions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  review_id bigint NOT NULL,
  answer_id bigint,
  question_id text CHECK (question_id ~ '^[A-Z]{2,6}-[0-9]{1,4}$'),
  kind text NOT NULL DEFAULT 'finding' CHECK (kind IN ('finding', 'conclusion')),
  control_ref text CHECK (length(control_ref) <= 40),
  severity text NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  description text CHECK (length(description) <= 4000),
  rationale text CHECK (length(rationale) <= 2000),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'edited_accepted', 'rejected')),
  decided_by bigint,
  decided_at timestamptz,
  reject_reason text CHECK (length(reject_reason) <= 1000),
  finding_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_ai_suggestions_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_ai_suggestions_assessment_id_key UNIQUE (workspace_id, assessment_id, id),
  CONSTRAINT tp_ai_suggestions_review_fk FOREIGN KEY (workspace_id, assessment_id, review_id)
    REFERENCES tp_ai_reviews (workspace_id, assessment_id, id),
  CONSTRAINT tp_ai_suggestions_answer_fk FOREIGN KEY (workspace_id, assessment_id, answer_id)
    REFERENCES tp_answers (workspace_id, assessment_id, id),
  CONSTRAINT tp_ai_suggestions_finding_fk FOREIGN KEY (workspace_id, assessment_id, finding_id)
    REFERENCES tp_findings (workspace_id, assessment_id, id) ON DELETE SET NULL (finding_id),
  CONSTRAINT tp_ai_suggestions_answer_question CHECK (answer_id IS NULL OR question_id IS NOT NULL),
  CONSTRAINT tp_ai_suggestions_decision CHECK (
    (status = 'pending' AND decided_by IS NULL AND decided_at IS NULL AND reject_reason IS NULL AND finding_id IS NULL)
    OR (status IN ('accepted', 'edited_accepted') AND decided_by IS NOT NULL AND decided_at IS NOT NULL AND reject_reason IS NULL)
    OR (status = 'rejected' AND decided_by IS NOT NULL AND decided_at IS NOT NULL AND finding_id IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_tp_ai_suggestions_review ON tp_ai_suggestions (workspace_id, review_id, id);
CREATE INDEX IF NOT EXISTS idx_tp_ai_suggestions_finding ON tp_ai_suggestions (workspace_id, finding_id) WHERE finding_id IS NOT NULL;

CREATE OR REPLACE FUNCTION tp_ai_suggestions_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  r_status text;
  f_source text;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_suggestions: an AI suggestion is never deleted';
  END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT status INTO r_status FROM tp_ai_reviews WHERE workspace_id = NEW.workspace_id AND id = NEW.review_id;
    IF r_status IS DISTINCT FROM 'running' OR NEW.status <> 'pending' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_ai_suggestions: suggestions are written, pending, by the run that produced them';
    END IF;
    RETURN NEW;
  END IF;
  IF ROW(NEW.id, NEW.workspace_id, NEW.assessment_id, NEW.review_id, NEW.answer_id, NEW.question_id, NEW.kind, NEW.control_ref,
         NEW.severity, NEW.title, NEW.description, NEW.rationale, NEW.created_at)
     IS DISTINCT FROM ROW(OLD.id, OLD.workspace_id, OLD.assessment_id, OLD.review_id, OLD.answer_id, OLD.question_id, OLD.kind,
         OLD.control_ref, OLD.severity, OLD.title, OLD.description, OLD.rationale, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_suggestions: what the AI suggested cannot change';
  END IF;
  -- The finding created on acceptance was removed later (ON DELETE SET NULL).
  IF OLD.status IN ('accepted', 'edited_accepted') AND NEW.finding_id IS NULL AND OLD.finding_id IS NOT NULL
     AND ROW(NEW.status, NEW.decided_by, NEW.decided_at, NEW.reject_reason)
         IS NOT DISTINCT FROM ROW(OLD.status, OLD.decided_by, OLD.decided_at, OLD.reject_reason) THEN
    RETURN NEW;
  END IF;
  IF OLD.status <> 'pending' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_suggestions: a decision on a suggestion is final';
  END IF;
  IF NEW.status IN ('accepted', 'edited_accepted') THEN
    SELECT source INTO f_source FROM tp_findings
     WHERE workspace_id = NEW.workspace_id AND assessment_id = NEW.assessment_id AND id = NEW.finding_id;
    IF f_source IS DISTINCT FROM 'ai_accepted' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_ai_suggestions: an accepted suggestion records the ai_accepted finding it created';
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_ai_suggestions_guard ON tp_ai_suggestions;
CREATE TRIGGER tp_ai_suggestions_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_ai_suggestions
  FOR EACH ROW EXECUTE FUNCTION tp_ai_suggestions_guard_fn();

CREATE TABLE IF NOT EXISTS tp_ai_suggestion_evidence (
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  suggestion_id bigint NOT NULL,
  evidence_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (workspace_id, suggestion_id, evidence_id),
  CONSTRAINT tp_ai_suggestion_evidence_suggestion_fk FOREIGN KEY (workspace_id, assessment_id, suggestion_id)
    REFERENCES tp_ai_suggestions (workspace_id, assessment_id, id),
  CONSTRAINT tp_ai_suggestion_evidence_evidence_fk FOREIGN KEY (workspace_id, assessment_id, evidence_id)
    REFERENCES tp_evidence (workspace_id, assessment_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_tp_ai_suggestion_evidence_evidence ON tp_ai_suggestion_evidence (workspace_id, evidence_id);

-- Links are written with their suggestion (while the run is running) and
-- never changed; a link goes when its file is deleted.
CREATE OR REPLACE FUNCTION tp_ai_suggestion_evidence_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_suggestion_evidence: a link cannot change';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM tp_ai_suggestions s JOIN tp_ai_reviews r ON r.workspace_id = s.workspace_id AND r.id = s.review_id
                  WHERE s.workspace_id = NEW.workspace_id AND s.id = NEW.suggestion_id AND r.status = 'running') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_ai_suggestion_evidence: links are written with their suggestion';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_ai_suggestion_evidence_guard ON tp_ai_suggestion_evidence;
CREATE TRIGGER tp_ai_suggestion_evidence_guard BEFORE INSERT OR UPDATE ON tp_ai_suggestion_evidence
  FOR EACH ROW EXECUTE FUNCTION tp_ai_suggestion_evidence_guard_fn();
