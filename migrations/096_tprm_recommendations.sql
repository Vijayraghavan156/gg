-- Third-party risk (TPRM) v2, Phase 2 slice 5: the recommendation.
-- See docs/tprm-v2-spec.md sections 1, 3, 4 and 6.
--
-- tp_recommendations: the firm's advice on an assessment, versioned per
-- assessment (1, 2, ...). Status:
--   draft -> in_review -> issued
--   in_review -> changes_requested -> in_review (the author revises the same
--     row; the version number only moves when a new version is started after
--     an issue, lib/tprm/recommendations.startNewVersion)
--   draft | in_review | changes_requested -> withdrawn (the author, before issue)
--   issued -> withdrawn only when a newer version of the same assessment is
--     issued (superseded_by_id names it), in the same transaction.
-- outcome is neutral (approve / approve_with_conditions / reject); the labels
-- depend on the assessment type (Onboard ... / Continue ...), see
-- lib/tprm/recommendations.js. residual_rating is the residual risk after the
-- assessment, on the tier scale.
--
-- Rules held here as well as in the domain layer:
--   - a recommendation is only created for an open assessment whose tier is
--     confirmed (trigger);
--   - the reviewer is never the author (CHECK);
--   - content (outcome, residual rating, rationale, valid until, author) can
--     change only while the row is draft or changes_requested, so the reviewer
--     issues exactly what was submitted, and an issued row never changes
--     (trigger); the one change an issued row allows is being superseded;
--   - one issued (live) recommendation and one unissued (draft / in review /
--     changes requested) recommendation per assessment (partial unique indexes);
--   - at issue: approve_with_conditions has at least one condition, any other
--     outcome has none, and every condition has an owner and a due date
--     (trigger);
--   - rows are never deleted, except with their whole workspace (trigger, as
--     for tp_events in migration 090).
--
-- tp_conditions: the conditions of an approve_with_conditions recommendation:
-- description, owner (vendor = the third party, or client), due date, status
-- (open only in Phase 2; tracking is Phase 5). Owner and due date may be blank
-- on a draft and are required at issue. Conditions change only while their
-- recommendation is draft or changes_requested (trigger): they are part of the
-- issued, immutable recommendation.
--
-- tp_assessments gains the recommendation stages in its named status CHECK:
--   tier_confirmed -> recommendation_draft (a draft exists, or changes were
--   requested) -> recommendation_in_review -> recommendation_issued.
-- Withdrawing a draft returns the assessment to recommendation_issued when an
-- earlier version is issued, otherwise to tier_confirmed. completed (after the
-- client decision, slice 6) and cancelled stay the closed statuses.
--
-- User columns carry no foreign key, as elsewhere in TPRM: the record
-- outlives the user. Deleting a whole workspace removes both tables with it
-- (lib/workspace-deletion.js suspends the guards; a direct workspace delete
-- cascades, and the guards let a delete through once the workspace is gone).

ALTER TABLE tp_assessments DROP CONSTRAINT IF EXISTS tp_assessments_status_check;
ALTER TABLE tp_assessments ADD CONSTRAINT tp_assessments_status_check
  CHECK (status IN ('scoping', 'tier_proposed', 'tier_confirmed',
    'recommendation_draft', 'recommendation_in_review', 'recommendation_issued',
    'completed', 'cancelled'));
ALTER TABLE tp_assessments DROP CONSTRAINT IF EXISTS tp_assessments_recommendation_after_tier;
ALTER TABLE tp_assessments ADD CONSTRAINT tp_assessments_recommendation_after_tier
  CHECK (status NOT IN ('recommendation_draft', 'recommendation_in_review', 'recommendation_issued')
    OR (final_tier IS NOT NULL AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL));

CREATE TABLE IF NOT EXISTS tp_recommendations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  version integer NOT NULL CHECK (version >= 1),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'in_review', 'changes_requested', 'issued', 'withdrawn')),
  outcome text CHECK (outcome IN ('approve', 'approve_with_conditions', 'reject')),
  residual_rating text CHECK (residual_rating IN ('low', 'medium', 'high', 'critical')),
  rationale text CHECK (length(rationale) <= 10000),
  valid_until date,
  author_id bigint NOT NULL,
  submitted_at timestamptz,
  reviewer_id bigint,
  reviewed_at timestamptz,
  review_comment text CHECK (length(review_comment) <= 2000),
  issued_at timestamptz,
  withdrawn_by bigint,
  withdrawn_at timestamptz,
  withdraw_reason text CHECK (length(withdraw_reason) <= 1000),
  superseded_by_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_recommendations_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_recommendations_version_key UNIQUE (workspace_id, assessment_id, version),
  CONSTRAINT tp_recommendations_assessment_fk FOREIGN KEY (workspace_id, assessment_id)
    REFERENCES tp_assessments (workspace_id, id),
  CONSTRAINT tp_recommendations_superseded_fk FOREIGN KEY (workspace_id, superseded_by_id)
    REFERENCES tp_recommendations (workspace_id, id),
  CONSTRAINT tp_recommendations_maker_checker CHECK (reviewer_id IS NULL OR reviewer_id <> author_id),
  -- Submitted, issued (and an issued row later superseded) carry everything.
  CONSTRAINT tp_recommendations_complete CHECK (
    (status NOT IN ('in_review', 'issued') AND issued_at IS NULL)
    OR (outcome IS NOT NULL AND residual_rating IS NOT NULL AND length(btrim(COALESCE(rationale, ''))) > 0
        AND valid_until IS NOT NULL AND submitted_at IS NOT NULL)),
  CONSTRAINT tp_recommendations_issued CHECK (
    (status <> 'issued' AND issued_at IS NULL)
    OR (issued_at IS NOT NULL AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL)),
  CONSTRAINT tp_recommendations_changes_requested CHECK (
    status <> 'changes_requested'
    OR (reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND length(btrim(COALESCE(review_comment, ''))) > 0)),
  CONSTRAINT tp_recommendations_withdrawn CHECK (
    (status <> 'withdrawn' AND withdrawn_at IS NULL AND superseded_by_id IS NULL)
    OR (status = 'withdrawn' AND withdrawn_at IS NOT NULL AND (
         (issued_at IS NULL AND superseded_by_id IS NULL AND withdrawn_by IS NOT NULL
           AND length(btrim(COALESCE(withdraw_reason, ''))) > 0)
      OR (issued_at IS NOT NULL AND superseded_by_id IS NOT NULL))))
);
-- One live issued recommendation, and one not yet issued, per assessment.
CREATE UNIQUE INDEX IF NOT EXISTS tp_recommendations_one_issued
  ON tp_recommendations (workspace_id, assessment_id) WHERE status = 'issued';
CREATE UNIQUE INDEX IF NOT EXISTS tp_recommendations_one_open
  ON tp_recommendations (workspace_id, assessment_id) WHERE status IN ('draft', 'in_review', 'changes_requested');
CREATE INDEX IF NOT EXISTS idx_tp_recommendations_status ON tp_recommendations (workspace_id, status);

CREATE TABLE IF NOT EXISTS tp_conditions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  recommendation_id bigint NOT NULL,
  position integer NOT NULL DEFAULT 1 CHECK (position >= 1),
  description text NOT NULL CHECK (length(btrim(description)) > 0 AND length(description) <= 2000),
  owner text CHECK (owner IN ('vendor', 'client')),
  due_date date,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_conditions_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_conditions_recommendation_fk FOREIGN KEY (workspace_id, recommendation_id)
    REFERENCES tp_recommendations (workspace_id, id)
);
CREATE INDEX IF NOT EXISTS idx_tp_conditions_recommendation ON tp_conditions (workspace_id, recommendation_id, position);

-- Creation, transitions, maker-checker at issue, the conditions rule at
-- issue, and immutability of everything but a draft's content.
CREATE OR REPLACE FUNCTION tp_recommendations_check_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  a record;
  n_conditions integer;
  n_incomplete integer;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT status, confirmed_at INTO a FROM tp_assessments
     WHERE workspace_id = NEW.workspace_id AND id = NEW.assessment_id;
    IF NOT FOUND OR a.confirmed_at IS NULL
       OR a.status NOT IN ('tier_confirmed', 'recommendation_draft', 'recommendation_in_review', 'recommendation_issued') THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: a recommendation needs an open assessment with a confirmed tier';
    END IF;
    IF NEW.status <> 'draft' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: a recommendation starts as a draft';
    END IF;
    RETURN NEW;
  END IF;

  -- UPDATE.
  IF OLD.status = 'withdrawn' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendations: a withdrawn recommendation cannot be changed';
  END IF;
  IF ROW(NEW.workspace_id, NEW.assessment_id, NEW.version, NEW.author_id, NEW.created_at)
     IS DISTINCT FROM ROW(OLD.workspace_id, OLD.assessment_id, OLD.version, OLD.author_id, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendations: the assessment, version and author of a recommendation never change';
  END IF;
  IF OLD.status NOT IN ('draft', 'changes_requested')
     AND ROW(NEW.outcome, NEW.residual_rating, NEW.rationale, NEW.valid_until)
         IS DISTINCT FROM ROW(OLD.outcome, OLD.residual_rating, OLD.rationale, OLD.valid_until) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendations: only a draft can be edited (' || OLD.status || ' rejected)';
  END IF;
  IF OLD.status = 'issued' THEN
    -- Issued is immutable; the only change is being superseded by a newer
    -- issued version of the same assessment.
    IF NEW.status <> 'withdrawn' OR NEW.superseded_by_id IS NULL
       OR ROW(NEW.submitted_at, NEW.reviewer_id, NEW.reviewed_at, NEW.review_comment, NEW.issued_at, NEW.withdrawn_by, NEW.withdraw_reason)
          IS DISTINCT FROM ROW(OLD.submitted_at, OLD.reviewer_id, OLD.reviewed_at, OLD.review_comment, OLD.issued_at, NULL::bigint, NULL::text) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: an issued recommendation is immutable';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM tp_recommendations r
       WHERE r.workspace_id = NEW.workspace_id AND r.id = NEW.superseded_by_id
         AND r.assessment_id = NEW.assessment_id AND r.version > NEW.version) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: an issued recommendation is only superseded by a later version of the same assessment';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status AND NOT (
       (OLD.status = 'draft' AND NEW.status IN ('in_review', 'withdrawn'))
    OR (OLD.status = 'changes_requested' AND NEW.status IN ('in_review', 'withdrawn'))
    OR (OLD.status = 'in_review' AND NEW.status IN ('issued', 'changes_requested', 'withdrawn'))) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendations: ' || OLD.status || ' cannot become ' || NEW.status;
  END IF;

  IF NEW.status = 'issued' THEN
    SELECT count(*), count(*) FILTER (WHERE owner IS NULL OR due_date IS NULL)
      INTO n_conditions, n_incomplete
      FROM tp_conditions WHERE workspace_id = NEW.workspace_id AND recommendation_id = NEW.id;
    IF NEW.outcome = 'approve_with_conditions' AND n_conditions = 0 THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: approve_with_conditions needs at least one condition';
    END IF;
    IF NEW.outcome <> 'approve_with_conditions' AND n_conditions > 0 THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: only approve_with_conditions carries conditions';
    END IF;
    IF n_incomplete > 0 THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_recommendations: every condition needs an owner and a due date at issue';
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_recommendations_check ON tp_recommendations;
CREATE TRIGGER tp_recommendations_check BEFORE INSERT OR UPDATE ON tp_recommendations
  FOR EACH ROW EXECUTE FUNCTION tp_recommendations_check_fn();

CREATE OR REPLACE FUNCTION tp_recommendations_no_delete_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
    MESSAGE = 'tp_recommendations are never deleted (' || lower(TG_OP) || ' rejected); a draft is withdrawn instead';
END;
$fn$;
DROP TRIGGER IF EXISTS tp_recommendations_no_delete ON tp_recommendations;
CREATE TRIGGER tp_recommendations_no_delete BEFORE DELETE ON tp_recommendations
  FOR EACH ROW EXECUTE FUNCTION tp_recommendations_no_delete_fn();
DROP TRIGGER IF EXISTS tp_recommendations_no_truncate ON tp_recommendations;
CREATE TRIGGER tp_recommendations_no_truncate BEFORE TRUNCATE ON tp_recommendations
  FOR EACH STATEMENT EXECUTE FUNCTION tp_recommendations_no_delete_fn();

-- Conditions change only with a draft (or changes requested) recommendation.
CREATE OR REPLACE FUNCTION tp_conditions_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  ws bigint;
  rec_id bigint;
  rec_status text;
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_conditions: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    ws := OLD.workspace_id; rec_id := OLD.recommendation_id;
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = ws) THEN
      RETURN OLD;
    END IF;
  ELSE
    ws := NEW.workspace_id; rec_id := NEW.recommendation_id;
    IF TG_OP = 'UPDATE' AND (NEW.workspace_id IS DISTINCT FROM OLD.workspace_id OR NEW.recommendation_id IS DISTINCT FROM OLD.recommendation_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: a condition never moves to another recommendation';
    END IF;
  END IF;
  SELECT status INTO rec_status FROM tp_recommendations WHERE workspace_id = ws AND id = rec_id;
  IF rec_status IS NOT NULL AND rec_status NOT IN ('draft', 'changes_requested') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_conditions: conditions change only while their recommendation is a draft (' || rec_status || ')';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_conditions_guard ON tp_conditions;
CREATE TRIGGER tp_conditions_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_conditions
  FOR EACH ROW EXECUTE FUNCTION tp_conditions_guard_fn();
DROP TRIGGER IF EXISTS tp_conditions_no_truncate ON tp_conditions;
CREATE TRIGGER tp_conditions_no_truncate BEFORE TRUNCATE ON tp_conditions
  FOR EACH STATEMENT EXECUTE FUNCTION tp_conditions_guard_fn();
