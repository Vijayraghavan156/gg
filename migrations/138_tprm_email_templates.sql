CREATE TABLE IF NOT EXISTS tp_email_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind ~ '^[a-z0-9_]{3,60}$'),
  subject text CHECK (length(subject) <= 200),
  headline text CHECK (length(headline) <= 200),
  opening text CHECK (length(opening) <= 2000),
  closing text CHECK (length(closing) <= 2000),
  updated_by bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_email_templates_one_per_kind UNIQUE (firm_id, kind)
);
