CREATE TABLE IF NOT EXISTS tp_finding_comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  finding_id bigint NOT NULL,
  author_kind text NOT NULL CHECK (author_kind IN ('firm', 'client')),
  author_user_id bigint NOT NULL,
  author_name text CHECK (length(author_name) <= 200),
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 4000),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_finding_comments_finding_fk FOREIGN KEY (workspace_id, assessment_id, finding_id)
    REFERENCES tp_findings (workspace_id, assessment_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_tp_finding_comments_finding ON tp_finding_comments (workspace_id, finding_id, id);
