-- Third-party risk (TPRM) v2, Phase 5A: condition follow-up.
-- See docs/tprm-v2-spec.md section 4e. Migrations 083-104 are applied and
-- frozen; everything here replaces their objects by name or adds new ones.
--
-- A condition of an approve_with_conditions recommendation is tracked once
-- the client decided "Onboard with conditions" / "Continue with conditions"
-- (a tp_client_decisions row with outcome approve_with_conditions on that
-- recommendation). Until then, and for every other decision, it stays open
-- and nothing about it changes. Lifecycle (tp_conditions.status):
--
--   open | changes_requested -> proof_submitted   (a proof is submitted)
--   proof_submitted -> verified                    (final)
--   proof_submitted -> changes_requested           (with a comment)
--   open | changes_requested -> waived             (a manager, with a reason
--                                                   and an optional expiry)
--   waived -> proof_submitted | waived             (only a waiver that has
--                                                   an expiry date; the domain
--                                                   allows it once that date
--                                                   has passed)
--
-- Overdue is computed (due date past, not verified, not waived or the waiver
-- expired); nothing is stored for it.
--
-- tp_condition_proofs: one row per submission, kept as history. Who sent it
-- (submitted_by_kind): client (a client user with the client owner or ISMS
-- manager role, in the client portal, on a client-owned condition),
-- consultant (a firm user uploading proof received from the third party, on
-- a third-party-owned condition) or vendor (reserved for a link for the third
-- party; refused until it exists). A submission is reviewed once: verified or
-- changes requested, never by the person who submitted it (CHECK). At most one
-- submission per condition waits for review (partial unique index).
--
-- tp_condition_proof_files: the files of a submission, stored by the app's
-- upload pipeline like tp_evidence (stored_path is never shown). Written with
-- their submission only; never changed.
--
-- Proof files are not tp_evidence rows: tp_evidence is frozen once the
-- assessment is completed (migration 098), and conditions are followed up
-- after that.
--
-- Rows are never deleted, except with their whole workspace (the guards let a
-- delete through once the workspace row is gone; lib/workspace-deletion.js
-- suspends them when it purges a client). User columns carry no foreign key,
-- as elsewhere in TPRM: the record outlives the user.

-- ---- tp_conditions: statuses and tracking columns ---------------------------

ALTER TABLE tp_conditions DROP CONSTRAINT IF EXISTS tp_conditions_status_check;
ALTER TABLE tp_conditions ADD CONSTRAINT tp_conditions_status_check
  CHECK (status IN ('open', 'proof_submitted', 'verified', 'changes_requested', 'waived'));

ALTER TABLE tp_conditions ADD COLUMN IF NOT EXISTS verified_by bigint;
ALTER TABLE tp_conditions ADD COLUMN IF NOT EXISTS verified_at timestamptz;
ALTER TABLE tp_conditions ADD COLUMN IF NOT EXISTS waived_by bigint;
ALTER TABLE tp_conditions ADD COLUMN IF NOT EXISTS waived_at timestamptz;
ALTER TABLE tp_conditions ADD COLUMN IF NOT EXISTS waive_reason text;
ALTER TABLE tp_conditions ADD COLUMN IF NOT EXISTS waive_until date;

ALTER TABLE tp_conditions DROP CONSTRAINT IF EXISTS tp_conditions_verified;
ALTER TABLE tp_conditions ADD CONSTRAINT tp_conditions_verified CHECK (
  (status = 'verified' AND verified_by IS NOT NULL AND verified_at IS NOT NULL)
  OR (status <> 'verified' AND verified_by IS NULL AND verified_at IS NULL));
ALTER TABLE tp_conditions DROP CONSTRAINT IF EXISTS tp_conditions_waived;
ALTER TABLE tp_conditions ADD CONSTRAINT tp_conditions_waived CHECK (
  (status = 'waived' AND waived_by IS NOT NULL AND waived_at IS NOT NULL
    AND length(btrim(COALESCE(waive_reason, ''))) > 0 AND length(waive_reason) <= 1000)
  OR (status <> 'waived' AND waived_by IS NULL AND waived_at IS NULL AND waive_reason IS NULL AND waive_until IS NULL));

-- (workspace_id, recommendation_id, id) so proofs can name the condition with
-- its recommendation.
DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tp_conditions_ws_recommendation_id_key') THEN
    ALTER TABLE tp_conditions ADD CONSTRAINT tp_conditions_ws_recommendation_id_key UNIQUE (workspace_id, recommendation_id, id);
  END IF;
END
$do$;

-- ---- tp_condition_proofs ------------------------------------------------------

CREATE TABLE IF NOT EXISTS tp_condition_proofs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  recommendation_id bigint NOT NULL,
  condition_id bigint NOT NULL,
  submitted_by_kind text NOT NULL CHECK (submitted_by_kind IN ('client', 'consultant', 'vendor')),
  submitted_by bigint,
  note text CHECK (length(note) <= 4000),
  submitted_at timestamptz NOT NULL DEFAULT now(),
  review_status text NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending', 'verified', 'changes_requested')),
  reviewed_by bigint,
  reviewed_at timestamptz,
  review_comment text CHECK (length(review_comment) <= 2000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_condition_proofs_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_condition_proofs_condition_id_key UNIQUE (workspace_id, condition_id, id),
  CONSTRAINT tp_condition_proofs_condition_fk FOREIGN KEY (workspace_id, recommendation_id, condition_id)
    REFERENCES tp_conditions (workspace_id, recommendation_id, id),
  CONSTRAINT tp_condition_proofs_submitter CHECK (submitted_by_kind = 'vendor' OR submitted_by IS NOT NULL),
  -- Maker-checker: the person who submitted a proof never reviews it.
  CONSTRAINT tp_condition_proofs_maker_checker CHECK (reviewed_by IS NULL OR reviewed_by IS DISTINCT FROM submitted_by),
  CONSTRAINT tp_condition_proofs_reviewed CHECK (
    (review_status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL AND review_comment IS NULL)
    OR (review_status = 'verified' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    OR (review_status = 'changes_requested' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL
        AND length(btrim(COALESCE(review_comment, ''))) > 0))
);
CREATE UNIQUE INDEX IF NOT EXISTS tp_condition_proofs_one_pending
  ON tp_condition_proofs (workspace_id, condition_id) WHERE review_status = 'pending';
CREATE INDEX IF NOT EXISTS idx_tp_condition_proofs_condition ON tp_condition_proofs (workspace_id, condition_id, id);

CREATE TABLE IF NOT EXISTS tp_condition_proof_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  condition_id bigint NOT NULL,
  proof_id bigint NOT NULL,
  original_name text NOT NULL CHECK (length(btrim(original_name)) BETWEEN 1 AND 255),
  stored_path text NOT NULL CHECK (stored_path ~ '^[A-Za-z0-9][A-Za-z0-9_.-]*$' AND length(stored_path) <= 400),
  size_bytes bigint NOT NULL CHECK (size_bytes >= 0),
  mime_type text CHECK (length(mime_type) <= 200),
  sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_condition_proof_files_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_condition_proof_files_proof_fk FOREIGN KEY (workspace_id, condition_id, proof_id)
    REFERENCES tp_condition_proofs (workspace_id, condition_id, id)
);
CREATE UNIQUE INDEX IF NOT EXISTS tp_condition_proof_files_stored_path_key ON tp_condition_proof_files (stored_path);
CREATE INDEX IF NOT EXISTS idx_tp_condition_proof_files_proof ON tp_condition_proof_files (workspace_id, proof_id, id);

-- ---- helpers -----------------------------------------------------------------

-- Whether a condition's recommendation is issued and the client decided on it
-- "with conditions": the one state in which a condition is tracked.
CREATE OR REPLACE FUNCTION tp_condition_trackable(p_workspace_id bigint, p_recommendation_id bigint) RETURNS boolean
LANGUAGE sql STABLE
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM tp_recommendations r
      JOIN tp_client_decisions d ON d.workspace_id = r.workspace_id AND d.recommendation_id = r.id
     WHERE r.workspace_id = p_workspace_id AND r.id = p_recommendation_id
       AND r.status = 'issued' AND d.outcome = 'approve_with_conditions')
$fn$;

-- Whether a user is a firm user of the firm that owns the workspace (and,
-- with p_manager, a manager there).
CREATE OR REPLACE FUNCTION tp_condition_firm_user(p_workspace_id bigint, p_user_id bigint, p_manager boolean) RETURNS boolean
LANGUAGE sql STABLE
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM users u JOIN workspaces w ON w.firm_id = u.firm_id
     WHERE w.id = p_workspace_id AND u.id = p_user_id AND u.user_type = 'firm' AND u.active = 1
       AND (NOT p_manager OR u.firm_role IN ('manager', 'firm_owner')))
$fn$;

-- ---- tp_conditions guard (replaces 096's) ------------------------------------
-- 096's rule is unchanged for a condition's content: insert, delete and any
-- change to position, description, owner or due date only while the
-- recommendation is a draft (or changes requested). New: the tracking columns
-- change only on a tracked condition (above), along the lifecycle.
CREATE OR REPLACE FUNCTION tp_conditions_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  ws bigint;
  rec_id bigint;
  rec_status text;
  content_changed boolean := true;
  tracking_changed boolean := false;
  latest record;
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_conditions: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    ws := OLD.workspace_id; rec_id := OLD.recommendation_id;
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = ws) THEN
      RETURN OLD;
    END IF;
  ELSE
    ws := NEW.workspace_id; rec_id := NEW.recommendation_id;
    IF TG_OP = 'UPDATE' AND (NEW.workspace_id IS DISTINCT FROM OLD.workspace_id OR NEW.recommendation_id IS DISTINCT FROM OLD.recommendation_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: a condition never moves to another recommendation';
    END IF;
  END IF;
  IF TG_OP = 'INSERT' AND (NEW.status <> 'open' OR NEW.verified_by IS NOT NULL OR NEW.waived_by IS NOT NULL) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_conditions: a condition starts open';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    content_changed := ROW(NEW.position, NEW.description, NEW.owner, NEW.due_date, NEW.created_at)
      IS DISTINCT FROM ROW(OLD.position, OLD.description, OLD.owner, OLD.due_date, OLD.created_at);
    tracking_changed := ROW(NEW.status, NEW.verified_by, NEW.verified_at, NEW.waived_by, NEW.waived_at, NEW.waive_reason, NEW.waive_until)
      IS DISTINCT FROM ROW(OLD.status, OLD.verified_by, OLD.verified_at, OLD.waived_by, OLD.waived_at, OLD.waive_reason, OLD.waive_until);
  END IF;
  SELECT status INTO rec_status FROM tp_recommendations WHERE workspace_id = ws AND id = rec_id;
  IF content_changed AND rec_status IS NOT NULL AND rec_status NOT IN ('draft', 'changes_requested') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_conditions: conditions change only while their recommendation is a draft (' || rec_status || ')';
  END IF;
  IF tracking_changed THEN
    IF NOT tp_condition_trackable(ws, rec_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: a condition is tracked only after the client decided on its recommendation with conditions';
    END IF;
    IF NOT (
         (OLD.status IN ('open', 'changes_requested') AND NEW.status IN ('proof_submitted', 'waived'))
      OR (OLD.status = 'proof_submitted' AND NEW.status IN ('verified', 'changes_requested'))
      OR (OLD.status = 'waived' AND OLD.waive_until IS NOT NULL AND NEW.status IN ('proof_submitted', 'waived'))) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: ' || OLD.status || ' cannot become ' || NEW.status;
    END IF;
    SELECT p.id, p.submitted_by, p.review_status, p.reviewed_by INTO latest FROM tp_condition_proofs p
     WHERE p.workspace_id = ws AND p.condition_id = NEW.id ORDER BY p.id DESC LIMIT 1;
    IF NEW.status = 'proof_submitted' AND (latest.id IS NULL OR latest.review_status <> 'pending') THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: proof_submitted needs a submitted proof waiting for review';
    END IF;
    IF NEW.status IN ('verified', 'changes_requested')
       AND (latest.id IS NULL OR latest.review_status <> NEW.status) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: the latest proof must be reviewed as ' || NEW.status;
    END IF;
    IF NEW.status = 'verified' AND (NEW.verified_by IS NOT DISTINCT FROM latest.submitted_by
       OR NEW.verified_by IS DISTINCT FROM latest.reviewed_by OR NOT tp_condition_firm_user(ws, NEW.verified_by, false)) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: a condition is verified by a firm user who did not submit the proof';
    END IF;
    IF NEW.status = 'waived' AND NOT tp_condition_firm_user(ws, NEW.waived_by, true) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_conditions: only a manager of the firm waives a condition';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_conditions_guard ON tp_conditions;
CREATE TRIGGER tp_conditions_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_conditions
  FOR EACH ROW EXECUTE FUNCTION tp_conditions_guard_fn();
DROP TRIGGER IF EXISTS tp_conditions_no_truncate ON tp_conditions;
CREATE TRIGGER tp_conditions_no_truncate BEFORE TRUNCATE ON tp_conditions
  FOR EACH STATEMENT EXECUTE FUNCTION tp_conditions_guard_fn();

-- ---- tp_condition_proofs guard -------------------------------------------------
CREATE OR REPLACE FUNCTION tp_condition_proofs_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  c record;
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_condition_proofs: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs are never deleted (delete rejected)';
  END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT id, owner, status, waive_until INTO c FROM tp_conditions
     WHERE workspace_id = NEW.workspace_id AND recommendation_id = NEW.recommendation_id AND id = NEW.condition_id;
    IF NOT FOUND OR NOT tp_condition_trackable(NEW.workspace_id, NEW.recommendation_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: proof is submitted only on a condition the client decided with';
    END IF;
    IF NOT (c.status IN ('open', 'changes_requested') OR (c.status = 'waived' AND c.waive_until IS NOT NULL)) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: the condition is ' || c.status || ', so no proof is submitted';
    END IF;
    IF NEW.review_status <> 'pending' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: a submission starts waiting for review';
    END IF;
    IF NEW.submitted_by_kind = 'vendor' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: proof through a link for the third party is not offered yet';
    END IF;
    IF NEW.submitted_by_kind = 'client' AND (c.owner <> 'client' OR NOT EXISTS (
        SELECT 1 FROM users u JOIN workspace_members m ON m.user_id = u.id
         WHERE u.id = NEW.submitted_by AND u.user_type = 'client' AND u.active = 1
           AND m.workspace_id = NEW.workspace_id AND m.role IN ('client_owner', 'client_admin', 'isms_manager'))) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: client proof is for a client-owned condition, from a client owner or ISMS manager of this client';
    END IF;
    IF NEW.submitted_by_kind = 'consultant' AND (c.owner <> 'vendor' OR NOT tp_condition_firm_user(NEW.workspace_id, NEW.submitted_by, false)) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: the firm uploads proof for a condition the third party owns';
    END IF;
    RETURN NEW;
  END IF;
  -- UPDATE: a submission is reviewed once; nothing else changes.
  IF ROW(NEW.id, NEW.workspace_id, NEW.recommendation_id, NEW.condition_id, NEW.submitted_by_kind, NEW.submitted_by, NEW.note,
         NEW.submitted_at, NEW.created_at)
     IS DISTINCT FROM ROW(OLD.id, OLD.workspace_id, OLD.recommendation_id, OLD.condition_id, OLD.submitted_by_kind, OLD.submitted_by,
         OLD.note, OLD.submitted_at, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs: a submission never changes';
  END IF;
  IF OLD.review_status <> 'pending' OR NEW.review_status = 'pending' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs: a submission is reviewed once';
  END IF;
  IF NOT tp_condition_firm_user(NEW.workspace_id, NEW.reviewed_by, false) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs: a firm user of this client''s firm reviews the proof';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_condition_proofs_guard ON tp_condition_proofs;
CREATE TRIGGER tp_condition_proofs_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_condition_proofs
  FOR EACH ROW EXECUTE FUNCTION tp_condition_proofs_guard_fn();
DROP TRIGGER IF EXISTS tp_condition_proofs_no_truncate ON tp_condition_proofs;
CREATE TRIGGER tp_condition_proofs_no_truncate BEFORE TRUNCATE ON tp_condition_proofs
  FOR EACH STATEMENT EXECUTE FUNCTION tp_condition_proofs_guard_fn();

-- ---- tp_condition_proof_files guard --------------------------------------------
CREATE OR REPLACE FUNCTION tp_condition_proof_files_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_condition_proof_files: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proof_files are never deleted (delete rejected)';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proof_files never change (update rejected)';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM tp_condition_proofs p
      WHERE p.workspace_id = NEW.workspace_id AND p.condition_id = NEW.condition_id AND p.id = NEW.proof_id
        AND p.review_status = 'pending') THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proof_files: files are added with their submission, before it is reviewed';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_condition_proof_files_guard ON tp_condition_proof_files;
CREATE TRIGGER tp_condition_proof_files_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_condition_proof_files
  FOR EACH ROW EXECUTE FUNCTION tp_condition_proof_files_guard_fn();
DROP TRIGGER IF EXISTS tp_condition_proof_files_no_truncate ON tp_condition_proof_files;
CREATE TRIGGER tp_condition_proof_files_no_truncate BEFORE TRUNCATE ON tp_condition_proof_files
