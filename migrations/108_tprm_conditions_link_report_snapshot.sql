-- Third-party risk (TPRM) v2, Phase 5 follow-up: a link for the third party to
-- send proof for the conditions it owns, and the recommendation report's
-- snapshot taken when a version is issued. See docs/tprm-v2-spec.md section
-- 4h. Migrations 083-107 are applied and frozen; everything here adds new
-- objects or replaces an earlier function by name (tp_condition_proofs_guard_fn
-- of 105).
--
-- tp_condition_links: a link for the third party (like tp_vendor_requests of
-- 099: only the sha256 of a 32-byte random token is stored, an expiry, a
-- revocation) that opens the open third-party-owned conditions of one
-- assessment's issued recommendation, once the client decided on it with
-- conditions. A separate table, not a purpose column on tp_vendor_requests:
-- those rows belong to a questionnaire (questionnaire_id NOT NULL, one active
-- link per questionnaire, a guard that needs an open questionnaire on an
-- assessment that is not frozen, revoked when the assessment completes), while
-- a conditions link exists only after completion and may have no
-- questionnaire at all. At most one active link per assessment. Revoked by the
-- firm, when a new one replaces it, or when every third-party-owned condition
-- is verified or waived. Never deleted.
--
-- tp_condition_proofs (changed): condition_link_id names the link a
-- submission came through; submitted_by_kind 'vendor' (reserved by 105) is now
-- accepted, only through an active, unexpired link of the same
-- recommendation, on a third-party-owned condition, with no submitting user.
--
-- tp_recommendation_snapshots: what the report of an issued version says
-- about the recommendation (outcome, residual, rationale, valid until, tier,
-- findings, conditions as issued, released files, questionnaire status), as
-- JSON text with its sha256 (checked here). One per recommendation; taken in
-- the issue transaction, or (versions issued before this migration) on the
-- first report generation, marked taken_after_issue. Never changed or deleted.
--
-- Guards let a delete through once the workspace row is gone (a direct
-- workspace delete cascades); lib/workspace-deletion.js suspends them when it
-- purges a client. User columns carry no foreign key, as elsewhere in TPRM.

-- ---- tp_condition_links -----------------------------------------------------

CREATE TABLE IF NOT EXISTS tp_condition_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  recommendation_id bigint NOT NULL,
  token_hash text NOT NULL CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  recipient_name text NOT NULL CHECK (length(btrim(recipient_name)) BETWEEN 1 AND 200),
  recipient_email text NOT NULL CHECK (length(recipient_email) BETWEEN 3 AND 320 AND recipient_email ~ '^[^[:space:]@]+@[^[:space:]@]+$'),
  expires_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  created_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_by bigint,
  revoked_at timestamptz,
  revoke_reason text CHECK (length(revoke_reason) <= 1000),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_condition_links_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_condition_links_token_hash_key UNIQUE (token_hash),
  CONSTRAINT tp_condition_links_assessment_fk FOREIGN KEY (workspace_id, assessment_id)
    REFERENCES tp_assessments (workspace_id, id),
  CONSTRAINT tp_condition_links_recommendation_fk FOREIGN KEY (workspace_id, recommendation_id)
    REFERENCES tp_recommendations (workspace_id, id),
  CONSTRAINT tp_condition_links_expiry CHECK (expires_at > created_at),
  CONSTRAINT tp_condition_links_revoked CHECK (
    (status = 'revoked' AND revoked_at IS NOT NULL AND length(btrim(COALESCE(revoke_reason, ''))) > 0)
    OR (status <> 'revoked' AND revoked_at IS NULL AND revoked_by IS NULL AND revoke_reason IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS tp_condition_links_one_active ON tp_condition_links (workspace_id, assessment_id)
  WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_tp_condition_links_assessment ON tp_condition_links (workspace_id, assessment_id, id);

CREATE OR REPLACE FUNCTION tp_condition_links_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_condition_links: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_links: a link is never deleted (it is revoked instead)';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'active' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_links: a link starts active';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM tp_recommendations r
        WHERE r.workspace_id = NEW.workspace_id AND r.id = NEW.recommendation_id AND r.assessment_id = NEW.assessment_id)
       OR NOT tp_condition_trackable(NEW.workspace_id, NEW.recommendation_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_links: a link is for the issued recommendation of its assessment, once the client decided on it with conditions';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM tp_conditions c
        WHERE c.workspace_id = NEW.workspace_id AND c.recommendation_id = NEW.recommendation_id AND c.owner = 'vendor'
          AND c.status <> 'verified' AND NOT (c.status = 'waived' AND c.waive_until IS NULL)) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_links: a link needs a third-party-owned condition that is not met yet';
    END IF;
    IF NOT tp_condition_firm_user(NEW.workspace_id, NEW.created_by, false) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_links: a firm user of this client''s firm creates the link';
    END IF;
    RETURN NEW;
  END IF;
  -- UPDATE: only an active link changes, and only to revoked.
  IF ROW(NEW.id, NEW.workspace_id, NEW.assessment_id, NEW.recommendation_id, NEW.token_hash, NEW.recipient_name,
         NEW.recipient_email, NEW.expires_at, NEW.created_by, NEW.created_at)
     IS DISTINCT FROM ROW(OLD.id, OLD.workspace_id, OLD.assessment_id, OLD.recommendation_id, OLD.token_hash, OLD.recipient_name,
         OLD.recipient_email, OLD.expires_at, OLD.created_by, OLD.created_at) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_links: the token, scope, recipient and expiry of a link never change';
  END IF;
  IF OLD.status <> 'active' AND ROW(NEW.status, NEW.revoked_by, NEW.revoked_at, NEW.revoke_reason)
     IS DISTINCT FROM ROW(OLD.status, OLD.revoked_by, OLD.revoked_at, OLD.revoke_reason) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_links: a revoked link cannot be changed';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_condition_links_guard ON tp_condition_links;
CREATE TRIGGER tp_condition_links_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_condition_links
  FOR EACH ROW EXECUTE FUNCTION tp_condition_links_guard_fn();
DROP TRIGGER IF EXISTS tp_condition_links_no_truncate ON tp_condition_links;
CREATE TRIGGER tp_condition_links_no_truncate BEFORE TRUNCATE ON tp_condition_links
  FOR EACH STATEMENT EXECUTE FUNCTION tp_condition_links_guard_fn();

-- ---- tp_condition_proofs: the link a third party's submission came through ---

ALTER TABLE tp_condition_proofs ADD COLUMN IF NOT EXISTS condition_link_id bigint;
DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tp_condition_proofs_link_fk') THEN
    ALTER TABLE tp_condition_proofs ADD CONSTRAINT tp_condition_proofs_link_fk FOREIGN KEY (workspace_id, condition_link_id)
      REFERENCES tp_condition_links (workspace_id, id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tp_condition_proofs_vendor_link') THEN
    ALTER TABLE tp_condition_proofs ADD CONSTRAINT tp_condition_proofs_vendor_link CHECK (
      (submitted_by_kind = 'vendor' AND condition_link_id IS NOT NULL AND submitted_by IS NULL)
      OR (submitted_by_kind <> 'vendor' AND condition_link_id IS NULL));
  END IF;
END
$do$;

-- Replaces 105's guard. Unchanged except: a vendor submission is accepted
-- through an active, unexpired link of the same recommendation on a
-- third-party-owned condition, and condition_link_id never changes.
CREATE OR REPLACE FUNCTION tp_condition_proofs_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
DECLARE
  c record;
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_condition_proofs: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs are never deleted (delete rejected)';
  END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT id, owner, status, waive_until INTO c FROM tp_conditions
     WHERE workspace_id = NEW.workspace_id AND recommendation_id = NEW.recommendation_id AND id = NEW.condition_id;
    IF NOT FOUND OR NOT tp_condition_trackable(NEW.workspace_id, NEW.recommendation_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: proof is submitted only on a condition the client decided with';
    END IF;
    IF NOT (c.status IN ('open', 'changes_requested') OR (c.status = 'waived' AND c.waive_until IS NOT NULL)) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: the condition is ' || c.status || ', so no proof is submitted';
    END IF;
    IF NEW.review_status <> 'pending' THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: a submission starts waiting for review';
    END IF;
    IF NEW.submitted_by_kind = 'vendor' AND (c.owner <> 'vendor' OR NEW.submitted_by IS NOT NULL OR NOT EXISTS (
        SELECT 1 FROM tp_condition_links l
         WHERE l.workspace_id = NEW.workspace_id AND l.id = NEW.condition_link_id AND l.recommendation_id = NEW.recommendation_id
           AND l.status = 'active' AND l.expires_at > now())) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: the third party sends proof through an active link, for a condition it owns';
    END IF;
    IF NEW.submitted_by_kind = 'client' AND (c.owner <> 'client' OR NOT EXISTS (
        SELECT 1 FROM users u JOIN workspace_members m ON m.user_id = u.id
         WHERE u.id = NEW.submitted_by AND u.user_type = 'client' AND u.active = 1
           AND m.workspace_id = NEW.workspace_id AND m.role IN ('client_owner', 'client_admin', 'isms_manager'))) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: client proof is for a client-owned condition, from a client owner or ISMS manager of this client';
    END IF;
    IF NEW.submitted_by_kind = 'consultant' AND (c.owner <> 'vendor' OR NOT tp_condition_firm_user(NEW.workspace_id, NEW.submitted_by, false)) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_condition_proofs: the firm uploads proof for a condition the third party owns';
    END IF;
    RETURN NEW;
  END IF;
  -- UPDATE: a submission is reviewed once; nothing else changes.
  IF ROW(NEW.id, NEW.workspace_id, NEW.recommendation_id, NEW.condition_id, NEW.submitted_by_kind, NEW.submitted_by, NEW.note,
         NEW.submitted_at, NEW.created_at, NEW.condition_link_id)
     IS DISTINCT FROM ROW(OLD.id, OLD.workspace_id, OLD.recommendation_id, OLD.condition_id, OLD.submitted_by_kind, OLD.submitted_by,
         OLD.note, OLD.submitted_at, OLD.created_at, OLD.condition_link_id) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs: a submission never changes';
  END IF;
  IF OLD.review_status <> 'pending' OR NEW.review_status = 'pending' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs: a submission is reviewed once';
  END IF;
  IF NOT tp_condition_firm_user(NEW.workspace_id, NEW.reviewed_by, false) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_condition_proofs: a firm user of this client''s firm reviews the proof';
  END IF;
  RETURN NEW;
END;
$fn$;

-- ---- tp_recommendation_snapshots ---------------------------------------------

CREATE TABLE IF NOT EXISTS tp_recommendation_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  recommendation_id bigint NOT NULL,
  content text NOT NULL CHECK (length(content) BETWEEN 2 AND 2000000),
  content_sha256 text NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
  taken_after_issue boolean NOT NULL,
  taken_by bigint,
  taken_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_recommendation_snapshots_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_recommendation_snapshots_one_per_recommendation UNIQUE (workspace_id, recommendation_id),
  CONSTRAINT tp_recommendation_snapshots_recommendation_fk FOREIGN KEY (workspace_id, recommendation_id)
    REFERENCES tp_recommendations (workspace_id, id),
  CONSTRAINT tp_recommendation_snapshots_assessment_fk FOREIGN KEY (workspace_id, assessment_id)
    REFERENCES tp_assessments (workspace_id, id),
  CONSTRAINT tp_recommendation_snapshots_object CHECK (jsonb_typeof(content::jsonb) = 'object'),
  CONSTRAINT tp_recommendation_snapshots_sha CHECK (content_sha256 = encode(sha256(convert_to(content, 'UTF8')), 'hex'))
);

CREATE OR REPLACE FUNCTION tp_recommendation_snapshots_guard_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'TRUNCATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation', MESSAGE = 'tp_recommendation_snapshots: truncate rejected';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces WHERE id = OLD.workspace_id) THEN
      RETURN OLD;
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendation_snapshots are never deleted (delete rejected)';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendation_snapshots never change (update rejected)';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM tp_recommendations r
      WHERE r.workspace_id = NEW.workspace_id AND r.id = NEW.recommendation_id AND r.assessment_id = NEW.assessment_id
        AND r.issued_at IS NOT NULL) THEN
    RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
      MESSAGE = 'tp_recommendation_snapshots: a snapshot is of an issued recommendation of its assessment';
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_recommendation_snapshots_guard ON tp_recommendation_snapshots;
CREATE TRIGGER tp_recommendation_snapshots_guard BEFORE INSERT OR UPDATE OR DELETE ON tp_recommendation_snapshots
  FOR EACH ROW EXECUTE FUNCTION tp_recommendation_snapshots_guard_fn();
DROP TRIGGER IF EXISTS tp_recommendation_snapshots_no_truncate ON tp_recommendation_snapshots;
CREATE TRIGGER tp_recommendation_snapshots_no_truncate BEFORE TRUNCATE ON tp_recommendation_snapshots
  FOR EACH STATEMENT EXECUTE FUNCTION tp_recommendation_snapshots_guard_fn();
