-- Third-party risk (TPRM) v2, Phase 2 slice 3b: assessments and their tier
-- step. See docs/tprm-v2-spec.md sections 3, 4 and 5.
--
-- tp_assessments: one row per assessment of a third party. type is
-- onboarding (a proposed third party) or reassessment (one in use); the
-- domain layer (lib/tprm/assessments.js) derives it from the third party's
-- status when the assessment starts.
--
-- status is the assessment's stage. This slice uses
--   scoping -> tier_proposed -> tier_confirmed, tier_proposed -> scoping
--   (sent back), and any open status -> cancelled.
-- Later slices add their stages (evidence, recommendation, client decision)
-- by replacing the named CHECK tp_assessments_status_check; completed and
-- cancelled are the closed statuses, already allowed so the "one open
-- assessment per third party" index below never has to change.
--
-- The criticality model version is pinned when the assessment starts
-- (criticality_model_id + criticality_model_version, the firm's active
-- version then). The tier is scored against that version only, so a later
-- model change never changes this assessment's tier. (firm_id,
-- criticality_model_id) references the model version on its composite key;
-- firm_id must be the workspace's firm (trigger below).
--
-- services_in_scope is a JSON array of { "id", "description" }: the third
-- party's services chosen for this assessment, with the description as it
-- was when chosen (services can be removed from the register later; the
-- assessment keeps what it covered). answers is { questionId: answerId }.
-- Tiers are the lowercase storage keys, as tp_third_parties.current_tier.
--
-- override_direction raise|lower|none is final_tier against scored_tier; a
-- reason is required for any override. client_designation_choice records the
-- consultant's choice on a reassessment where the client designated the
-- third party Critical and the questions score lower (spec section 5);
-- client_designation_used is true when the final tier came from the client's
-- designation.
--
-- The proposer can never confirm (CHECK), and the client decision owner,
-- when set, must be a client user of the same workspace with the client
-- owner or ISMS manager role (trigger). User columns carry no foreign key,
-- as for the audit log (migration 086): the record outlives the user.
--
-- tp_events gains the composite key (workspace_id, assessment_id) ->
-- tp_assessments that slice 1 left for this slice. Deleting a whole
-- workspace removes events and assessments together (lib/workspace-deletion.js
-- orders by foreign keys; a direct workspace delete cascades in one statement).

CREATE TABLE IF NOT EXISTS tp_assessments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  firm_id bigint NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  third_party_id bigint NOT NULL,
  type text NOT NULL CHECK (type IN ('onboarding', 'reassessment')),
  status text NOT NULL DEFAULT 'scoping',
  services_in_scope jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(services_in_scope) = 'array'),
  criticality_model_id bigint NOT NULL,
  criticality_model_version integer NOT NULL CHECK (criticality_model_version >= 1),
  answers jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(answers) = 'object'),
  scored_tier text CHECK (scored_tier IN ('critical', 'high', 'medium', 'low')),
  deciding_question_id text CHECK (length(deciding_question_id) <= 40),
  deciding_answer_id text CHECK (length(deciding_answer_id) <= 40),
  tier_explanation text CHECK (length(tier_explanation) <= 400),
  final_tier text CHECK (final_tier IN ('critical', 'high', 'medium', 'low')),
  override_direction text NOT NULL DEFAULT 'none' CHECK (override_direction IN ('none', 'raise', 'lower')),
  override_reason text CHECK (length(override_reason) <= 1000),
  client_designation_choice text CHECK (client_designation_choice IN ('keep_client_designation', 'use_scored_tier')),
  client_designation_used boolean NOT NULL DEFAULT false,
  proposed_by bigint,
  proposed_at timestamptz,
  confirmed_by bigint,
  confirmed_at timestamptz,
  returned_by bigint,
  returned_at timestamptz,
  return_comment text CHECK (length(return_comment) <= 2000),
  cancelled_by bigint,
  cancelled_at timestamptz,
  cancel_reason text CHECK (length(cancel_reason) <= 1000),
  lead_consultant_id bigint,
  reviewer_id bigint,
  client_decision_owner_id bigint,
  due_date date,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  CONSTRAINT tp_assessments_status_check
    CHECK (status IN ('scoping', 'tier_proposed', 'tier_confirmed', 'completed', 'cancelled')),
  CONSTRAINT tp_assessments_workspace_id_id_key UNIQUE (workspace_id, id),
  CONSTRAINT tp_assessments_third_party_fk FOREIGN KEY (workspace_id, third_party_id)
    REFERENCES tp_third_parties (workspace_id, id),
  CONSTRAINT tp_assessments_model_fk FOREIGN KEY (firm_id, criticality_model_id)
    REFERENCES tp_criticality_models (firm_id, id),
  CONSTRAINT tp_assessments_override_reason CHECK (
    override_direction = 'none' OR length(btrim(COALESCE(override_reason, ''))) > 0),
  CONSTRAINT tp_assessments_override_tier CHECK (
    override_direction = 'none' OR (final_tier IS NOT NULL AND scored_tier IS NOT NULL AND final_tier <> scored_tier)),
  CONSTRAINT tp_assessments_proposed CHECK (
    status NOT IN ('tier_proposed', 'tier_confirmed')
    OR (scored_tier IS NOT NULL AND final_tier IS NOT NULL AND proposed_by IS NOT NULL AND proposed_at IS NOT NULL)),
  CONSTRAINT tp_assessments_confirmed CHECK (
    status <> 'tier_confirmed' OR (confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL)),
  CONSTRAINT tp_assessments_maker_checker CHECK (
    confirmed_by IS NULL OR proposed_by IS NULL OR confirmed_by <> proposed_by),
  CONSTRAINT tp_assessments_cancelled CHECK (
    status <> 'cancelled' OR (cancelled_at IS NOT NULL AND length(btrim(COALESCE(cancel_reason, ''))) > 0))
);
-- One open assessment per third party.
CREATE UNIQUE INDEX IF NOT EXISTS tp_assessments_one_open
  ON tp_assessments (workspace_id, third_party_id) WHERE status NOT IN ('completed', 'cancelled');
CREATE INDEX IF NOT EXISTS idx_tp_assessments_third_party ON tp_assessments (workspace_id, third_party_id, created_at);
CREATE INDEX IF NOT EXISTS idx_tp_assessments_status ON tp_assessments (workspace_id, status);
CREATE INDEX IF NOT EXISTS idx_tp_assessments_model ON tp_assessments (firm_id, criticality_model_id);

CREATE OR REPLACE FUNCTION tp_assessments_check_fn() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.workspace_id IS DISTINCT FROM OLD.workspace_id OR NEW.firm_id IS DISTINCT FROM OLD.firm_id THEN
    IF NOT EXISTS (SELECT 1 FROM workspaces w WHERE w.id = NEW.workspace_id AND w.firm_id = NEW.firm_id) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_assessments: firm_id must be the firm of the workspace';
    END IF;
  END IF;
  IF NEW.client_decision_owner_id IS NOT NULL
     AND (TG_OP = 'INSERT' OR NEW.client_decision_owner_id IS DISTINCT FROM OLD.client_decision_owner_id) THEN
    IF NOT EXISTS (
      SELECT 1 FROM users u JOIN workspace_members m ON m.user_id = u.id
       WHERE u.id = NEW.client_decision_owner_id AND u.user_type = 'client'
         AND m.workspace_id = NEW.workspace_id
         AND m.role IN ('client_owner', 'client_admin', 'isms_manager')
    ) THEN
      RAISE EXCEPTION USING ERRCODE = 'integrity_constraint_violation',
        MESSAGE = 'tp_assessments: the client decision owner must be a client owner or ISMS manager of this client';
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS tp_assessments_check ON tp_assessments;
CREATE TRIGGER tp_assessments_check BEFORE INSERT OR UPDATE ON tp_assessments
  FOR EACH ROW EXECUTE FUNCTION tp_assessments_check_fn();

-- tp_events -> tp_assessments, as 091 did for third parties: validated
-- straight away when every existing assessment event points at a real
-- assessment (always true on a fresh install), otherwise left NOT VALID
-- (still enforced for every new event) so a database carrying older test
-- events still boots.
DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tp_events_assessment_fk') THEN
    ALTER TABLE tp_events ADD CONSTRAINT tp_events_assessment_fk FOREIGN KEY (workspace_id, assessment_id)
      REFERENCES tp_assessments (workspace_id, id) NOT VALID;
    IF NOT EXISTS (
      SELECT 1 FROM tp_events e
       WHERE e.assessment_id IS NOT NULL
         AND NOT EXISTS (SELECT 1 FROM tp_assessments a WHERE a.workspace_id = e.workspace_id AND a.id = e.assessment_id)
    ) THEN
      ALTER TABLE tp_events VALIDATE CONSTRAINT tp_events_assessment_fk;
    ELSE
      RAISE NOTICE 'tp_events_assessment_fk left NOT VALID: older events reference assessments that do not exist';
    END IF;
  END IF;
END
$do$;
