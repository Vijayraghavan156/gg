CREATE TABLE IF NOT EXISTS tp_clarification_drafts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  assessment_id bigint NOT NULL,
  questionnaire_id bigint NOT NULL,
  question_id text NOT NULL CHECK (question_id ~ '^[A-Z]{2,6}-[0-9]{1,4}$'),
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tp_clarification_drafts_questionnaire_fk FOREIGN KEY (workspace_id, assessment_id, questionnaire_id)
    REFERENCES tp_questionnaires (workspace_id, assessment_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_tp_clarification_drafts_questionnaire ON tp_clarification_drafts (workspace_id, questionnaire_id, id);
